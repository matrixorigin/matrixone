// Regenerates pkg/container/types/narrow_float_cuda_golden_test.go from CUDA's host FP8/FP4
// conversions:
//
//   cd optools/gpu && pixi run --frozen sh -c \
//     'nvcc -std=c++17 -o /tmp/golden_gen ../../cgo/cuvs/test/narrow_float_golden_gen.cu && /tmp/golden_gen'
//
// The output is prefixed with the license header and gofmt-ed.
#include <cuda_fp8.h>
#include <cuda_fp4.h>
#include <cstdio>
#include <cstdint>
#include <cstring>
#include <cmath>
#include <vector>

static uint32_t f2bits(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }

int main() {
    std::vector<float> in;
    for (int c = 0; c < 256; c++) {
        __nv_fp8_e4m3 a; a.__x = (__nv_fp8_storage_t)c;
        __nv_fp8_e4m3 b; b.__x = (__nv_fp8_storage_t)(c + 1);
        float va = (float)a, vb = (float)b;
        if (std::isnan(va)) continue;
        in.push_back(va);
        if (!std::isnan(vb) && c != 0x7f && c != 0xff && ((c ^ (c + 1)) & 0x80) == 0) {
            float mid = 0.5f * (va + vb);
            in.push_back(mid);
            in.push_back(std::nextafter(mid, INFINITY));
            in.push_back(std::nextafter(mid, -INFINITY));
        }
    }
    const float f4[8] = {0, 0.5f, 1, 1.5f, 2, 3, 4, 6};
    for (int s = -1; s <= 1; s += 2)
        for (int i = 0; i < 7; i++) {
            float mid = s * 0.5f * (f4[i] + f4[i + 1]);
            in.push_back(mid);
            in.push_back(std::nextafter(mid, INFINITY));
            in.push_back(std::nextafter(mid, -INFINITY));
        }
    for (float v : {0.0f, -0.0f, 448.0f, 464.0f, 480.0f, 1e30f, -1e30f, INFINITY, -INFINITY,
                    6.0f, 7.0f, -7.0f, 1e-30f, -1e-30f, 0.0009765625f, 0.00048828125f, 0.000732421875f})
        in.push_back(v);

    printf("// Code generated by cgo/cuvs/test/narrow_float_golden_gen.cu (CUDA %d.%d). DO NOT EDIT.\n\n",
           CUDART_VERSION / 1000, (CUDART_VERSION % 1000) / 10);
    printf("package types\n\n");
    printf("// cudaFloat8Decode[c] is the float32 bit pattern of e4m3 code c.\n");
    printf("var cudaFloat8Decode = [256]uint32{");
    for (int c = 0; c < 256; c++) {
        __nv_fp8_e4m3 a; a.__x = (__nv_fp8_storage_t)c;
        printf("%s0x%08x,", c % 8 == 0 ? "\n\t" : " ", f2bits((float)a));
    }
    printf("\n}\n\n");
    printf("// cudaFloat4Decode[c] is the float32 bit pattern of e2m1 code c.\n");
    printf("var cudaFloat4Decode = [16]uint32{");
    for (int c = 0; c < 16; c++) {
        __nv_fp4_e2m1 a; a.__x = (__nv_fp4_storage_t)c;
        printf("%s0x%08x,", c % 8 == 0 ? "\n\t" : " ", f2bits((float)a));
    }
    printf("\n}\n\n");
    printf("// cudaNarrowEncode lists float32 input bits with the CUDA e4m3 (__NV_SATFINITE) and\n");
    printf("// e2m1 (round-to-nearest) encodings.\n");
    printf("var cudaNarrowEncode = []struct {\n\tin  uint32\n\tf8  uint8\n\tf4  uint8\n}{\n");
    for (float v : in) {
        uint8_t o8 = __nv_cvt_float_to_fp8(v, __NV_SATFINITE, __NV_E4M3);
        uint8_t o4 = __nv_cvt_float_to_fp4(v, __NV_E2M1, cudaRoundNearest);
        printf("\t{0x%08x, 0x%02x, 0x%x},\n", f2bits(v), o8, o4);
    }
    printf("}\n\n");
    float2 pair = make_float2(1.0f, 6.0f);
    printf("// cudaFloat4PairOneSix is the byte __nv_cvt_float2_to_fp4x2 packs for (x=1.0, y=6.0).\n");
    printf("const cudaFloat4PairOneSix = 0x%02x\n", __nv_cvt_float2_to_fp4x2(pair, __NV_E2M1, cudaRoundNearest));
    fprintf(stderr, "encode cases: %zu\n", in.size());
    return 0;
}
