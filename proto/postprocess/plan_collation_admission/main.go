// Generate typed admission paths from the actual protobuf owner graph.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
)

func main() {
	if len(os.Args) != 3 {
		panic("usage: plan_collation_admission input.pb.go output.go")
	}
	result, err := generate(os.Args[1])
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(os.Args[2], result, 0644); err != nil {
		panic(err)
	}
}

func generate(input string) ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), input, nil, 0)
	if err != nil {
		return nil, err
	}
	structs := map[string]*ast.StructType{}
	methods := map[string]string{}
	impls := map[string][]string{}
	for _, decl := range file.Decls {
		g, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range g.Specs {
			t, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			switch value := t.Type.(type) {
			case *ast.StructType:
				structs[t.Name.Name] = value
			case *ast.InterfaceType:
				for _, field := range value.Methods.List {
					for _, name := range field.Names {
						if name.Name == t.Name.Name {
							methods[name.Name] = t.Name.Name
						}
					}
				}
			}
		}
	}
	for _, decl := range file.Decls {
		f, ok := decl.(*ast.FuncDecl)
		if !ok || f.Recv == nil || methods[f.Name.Name] == "" {
			continue
		}
		ptr, ok := f.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		name, ok := ptr.X.(*ast.Ident)
		if ok {
			impls[methods[f.Name.Name]] = append(impls[methods[f.Name.Name]], name.Name)
		}
	}
	reachable := map[string]bool{"Type": true, "TableDef": true, "IndexDef": true}
	var contains func(ast.Expr) bool
	contains = func(e ast.Expr) bool {
		switch t := e.(type) {
		case *ast.Ident:
			return reachable[t.Name]
		case *ast.StarExpr:
			return contains(t.X)
		case *ast.ArrayType:
			return contains(t.Elt)
		case *ast.MapType:
			return contains(t.Value)
		}
		return false
	}
	for changed := true; changed; {
		changed = false
		for name, s := range structs {
			if reachable[name] {
				continue
			}
			for _, field := range s.Fields.List {
				if contains(field.Type) {
					reachable[name], changed = true, true
					break
				}
			}
		}
		for name, variants := range impls {
			for _, variant := range variants {
				if reachable[variant] && !reachable[name] {
					reachable[name], changed = true, true
				}
			}
		}
	}
	var names []string
	for name := range reachable {
		if structs[name] != nil {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	// Only cyclic owner paths require pointer bookkeeping.
	graph := map[string][]string{}
	var refs func(ast.Expr) []string
	refs = func(e ast.Expr) []string {
		switch t := e.(type) {
		case *ast.Ident:
			if reachable[t.Name] {
				return []string{t.Name}
			}
		case *ast.StarExpr:
			return refs(t.X)
		case *ast.ArrayType:
			return refs(t.Elt)
		case *ast.MapType:
			return refs(t.Value)
		}
		return nil
	}
	for _, name := range names {
		for _, field := range structs[name].Fields.List {
			graph[name] = append(graph[name], refs(field.Type)...)
		}
	}
	for name, variants := range impls {
		graph[name] = append(graph[name], variants...)
	}
	// Guard recursive graph roots once, not every oneof wrapper on the
	// same cycle. Any new cycle not passing these roots is also detected.
	guard := map[string]bool{"Expr": true, "Plan": true, "Query": true}
	cyclic := map[string]bool{}
	for _, name := range names {
		visited := map[string]bool{}
		var returns func(string) bool
		returns = func(current string) bool {
			for _, next := range graph[current] {
				if guard[next] {
					continue
				}
				if next == name {
					return true
				}
				if !visited[next] {
					visited[next] = true
					if returns(next) {
						return true
					}
				}
			}
			return false
		}
		cyclic[name] = guard[name] || returns(name)
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by proto/postprocess/plan_collation_admission; DO NOT EDIT.\npackage plan")
	fmt.Fprintln(&b, "type legacyCollationVisitor struct { inline [32]any; count int; seen map[any]struct{} }")
	fmt.Fprintln(&b, "func (v *legacyCollationVisitor) visited(p any) bool { if v.seen != nil { if _, ok := v.seen[p]; ok { return true }; v.seen[p] = struct{}{}; return false }; for _, old := range v.inline[:v.count] { if old == p { return true } }; if v.count < len(v.inline) { v.inline[v.count] = p; v.count++; return false }; v.seen = make(map[any]struct{}, 2*len(v.inline)); for _, old := range v.inline { v.seen[old] = struct{}{} }; v.seen[p] = struct{}{}; return false }")
	fmt.Fprintln(&b, "func (v *legacyCollationVisitor) typed(owner any) (bool, error) { switch p := owner.(type) {")
	for _, name := range names {
		fmt.Fprintf(&b, "case *%s: return true, v.walk%s(p)\n", name, name)
	}
	for _, name := range []string{"Type", "TableDef", "IndexDef"} {
		fmt.Fprintf(&b, "case %s: return true, v.walk%s(&p)\n", name, name)
	}
	fmt.Fprintln(&b, "case []*Expr: for _, p := range p { if err := v.walkExpr(p); err != nil { return true, err } }; return true, nil")
	fmt.Fprintln(&b, "case []Expr: for i := range p { if err := v.walkExpr(&p[i]); err != nil { return true, err } }; return true, nil")
	fmt.Fprintln(&b, "}; return false, nil }")
	var emit func(ast.Expr, string, int)
	emit = func(e ast.Expr, access string, depth int) {
		if !contains(e) {
			return
		}
		switch t := e.(type) {
		case *ast.StarExpr:
			name := t.X.(*ast.Ident).Name
			fmt.Fprintf(&b, "if err := v.walk%s(%s); err != nil { return err }\n", name, access)
		case *ast.Ident:
			if structs[t.Name] != nil {
				fmt.Fprintf(&b, "if err := v.walk%s(&%s); err != nil { return err }\n", t.Name, access)
			} else {
				fmt.Fprintf(&b, "switch x := %s.(type) {\n", access)
				variants := append([]string(nil), impls[t.Name]...)
				sort.Strings(variants)
				for _, variant := range variants {
					if reachable[variant] {
						fmt.Fprintf(&b, "case *%s: if err := v.walk%s(x); err != nil { return err }\n", variant, variant)
					}
				}
				fmt.Fprintln(&b, "}")
			}
		case *ast.ArrayType:
			item := fmt.Sprintf("item%d", depth)
			fmt.Fprintf(&b, "for _, %s := range %s {\n", item, access)
			emit(t.Elt, item, depth+1)
			fmt.Fprintln(&b, "}")
		case *ast.MapType:
			item := fmt.Sprintf("item%d", depth)
			fmt.Fprintf(&b, "for _, %s := range %s {\n", item, access)
			emit(t.Value, item, depth+1)
			fmt.Fprintln(&b, "}")
		}
	}
	for _, name := range names {
		fmt.Fprintf(&b, "func (v *legacyCollationVisitor) walk%s(p *%s) error { if p == nil { return nil };\n", name, name)
		if name == "Type" {
			fmt.Fprintln(&b, "return requireLegacyType(*p) }")
			continue
		}
		if cyclic[name] {
			fmt.Fprintln(&b, "if v.visited(p) { return nil }")
		}
		if name == "TableDef" {
			fmt.Fprintln(&b, "if err := requireLegacySchema(p.DefaultCharset, p.CollationVersion, p.KeyFormat); err != nil { return err }")
		}
		if name == "IndexDef" {
			fmt.Fprintln(&b, "if err := requireLegacySchema(0, 0, p.KeyFormat); err != nil { return err }")
		}
		for _, field := range structs[name].Fields.List {
			for _, fieldName := range field.Names {
				emit(field.Type, "p."+fieldName.Name, 0)
			}
		}
		fmt.Fprintln(&b, "return nil }")
	}
	return format.Source(b.Bytes())
}
