// Data branch merge sequence reconciliation (design §4 B).
//
// A merge copies rows whose keys were generated by a branch-local sequence
// into the destination table without calling the destination's DEFAULT; the
// destination sequence would stay behind and a later default INSERT would
// regenerate an already-present key (#30359). While typed rows are live
// during apply, a merge-scoped tracker accumulates the extreme
// sequence-generated values per owner-database sequence identity
// (watermarks). After all apply batches flush successfully and before the
// merge statement reports success, one reconcile unit runs, partitioned by
// generation visibility exactly like allocation (§4 D): committed
// generations advance in one fresh committed transaction under a
// sequenceReconcilePlanHook is a test-only seam for the design §9 L2/K2
// deterministic barrier oracles: it fires once per committed-partition
// attempt after the unit's identities are resolved and sorted into canonical
// order, before the first acquisition step. Production callers never install
// one; the lookup is a single context read per reconcile attempt.
type sequenceReconcilePlanHook interface {
	AfterPlan(ids []uint64)
}

type sequenceReconcilePlanHookKey struct{}

// withSequenceReconcilePlanHook attaches the barrier-oracle hook. It is
// unexported on purpose: no production path carries a hook.
func withSequenceReconcilePlanHook(ctx context.Context, h sequenceReconcilePlanHook) context.Context {
	return context.WithValue(ctx, sequenceReconcilePlanHookKey{}, h)
}

// validate-before-proceed catalog lock order; transaction-local generations
// (in-txn CLONE destinations) advance inside the caller transaction so rows,
// counter growth, and the generation itself share one commit/rollback fate.
//
// Every advance is a monotonic conditional UPDATE, so merge retries are
// no-ops and concurrent allocation can never be regressed. A NO CYCLE
// watermark at the sequence's edge fails the merge failure-atomically
// instead of installing a counter that can never issue.

// sequenceWatermarkKey identifies one sequence identity owned by the merge
// destination's database. Map keys are normalized per the effective
// lower_case_table_names — folded only when the session folds — while the
// watermark keeps the resolved spelling for engine lookup and SQL.
type sequenceWatermarkKey struct {
	db    string
	table string
}

// seqDomainArm is the running extreme over the captured merged keys
// representable in one sequence storage domain. max/min are plain
// magnitudes for the unsigned domains and sign-extended bits for the
// signed domains; has marks that at least one captured key fit.
type seqDomainArm struct {
	max uint64
	min uint64
	has bool
}

func (a *seqDomainArm) addValue(v uint64, signedDomain bool) {
	if signedDomain {
		if !a.has || int64(v) > int64(a.max) {
			a.max = v
		}
		if !a.has || int64(v) < int64(a.min) {
			a.min = v
		}
	} else {
		if !a.has || v > a.max {
			a.max = v
		}
		if !a.has || v < a.min {
			a.min = v
		}
	}
	a.has = true
}

type sequenceWatermark struct {
	key   sequenceWatermarkKey
	db    string // original spelling
	table string // original spelling
	// Presence-flagged per-storage-domain extrema. The merged column's
	// type never decides the numeric domain (#30359 pre-PR review): a
	// value can arrive through a cast-wrapped column (e.g. VARCHAR)
	// whose signedness says nothing about the sequence's domain, so the
	// tracker keeps one arm per sequence storage domain and
	// CheckSequenceWatermark picks the arm after reading the sequence's
	// own metadata row. Each captured value feeds ONLY the arms whose
	// domain can REPRESENT it: a negative value feeds no unsigned arm, a
	// value above MaxInt64 feeds no signed arm, and a 70000 feeds no
	// 16-bit arm. Folding foreign-domain bit patterns into an arm would
	// conflate distinct numbers (signed -1 and unsigned MaxUint64 share
	// one bit pattern) and false-exhaust or mis-order the reconcile
	// (#30359 pre-PR review, watermark domain conflation and width).
	arms [function.SequenceDomainCount]seqDomainArm

	rowsCount int64
}

// accumulate folds one classified merged value into every storage-domain
// arm that can represent it.
func (wm *sequenceWatermark) accumulate(val sequenceWatermarkValue) {
	for i := 0; i < int(function.SequenceDomainCount); i++ {
		d := function.SequenceDomain(i)
		arm := &wm.arms[i]
		if d.UnsignedDomain() {
			if val.hasU && d.ContainsUint64(val.u) {
				arm.addValue(val.u, false)
			}
			if val.hasS {
				if sv := int64(val.s); d.ContainsInt64(sv) {
					arm.addValue(uint64(sv), false)
				}
			}
			continue
		}
		if val.hasS && d.ContainsInt64(int64(val.s)) {
			arm.addValue(val.s, true)
		}
		if val.hasU && d.ContainsUint64(val.u) {
			arm.addValue(uint64(int64(val.u)), true)
		}
	}
}

// sequenceWatermarkTracker is the merge-scoped watermark accumulator. cols
// maps destination column indices whose restored default is a reconcilable
// shape: a single nextval with constant arguments (planner-inserted
// assignment casts stripped), pinned or owned by the destination database.
// Defaults pinning another database are left alone, matching the §4 A
// ownership model. lctn carries the session's effective
// lower_case_table_names so identities are keyed exactly as the engine
// resolves them — folding under lctn=1, case-sensitively under lctn=0.
type sequenceWatermarkTracker struct {
	dstDB string
	lctn  int64
	cols  map[int]sequenceWatermarkKey
	items map[sequenceWatermarkKey]*sequenceWatermark
}

// nameKey normalizes a catalog identity spelling for map keying per the
// effective lower_case_table_names; the engine applies the same rule when
// resolving the name, so the key never collapses identities that are
// distinct in case-sensitive mode.
func (t *sequenceWatermarkTracker) nameKey(name string) string {
	if t.lctn == 1 {
		return strings.ToLower(name)
	}
	return name
}

// sameDB reports whether a default-pinned database names the destination
// database under the effective case semantics.
func (t *sequenceWatermarkTracker) sameDB(db string) bool {
	if t.lctn == 1 {
		return strings.EqualFold(db, t.dstDB)
	}
	return db == t.dstDB
}

// newSequenceWatermarkTracker inspects the merge destination's defaults
// once per merge.
func newSequenceWatermarkTracker(ctx context.Context, tblStuff tableStuff, lctn int64) (*sequenceWatermarkTracker, error) {
	tracker := &sequenceWatermarkTracker{
		lctn:  lctn,
		cols:  make(map[int]sequenceWatermarkKey),
		items: make(map[sequenceWatermarkKey]*sequenceWatermark),
	}
	// The merge destination is baseRel (the table receiving rows), not
	// tarRel: tarRel is the first (row-source) endpoint. Watermarks must
	// reconcile the sequence owned by the destination database against the
	// destination's defaults, mapped back to the apply-row layout by name so
	// renamed/restored columns still match.
	if tblStuff.baseRel == nil || tblStuff.tarRel == nil {
		return tracker, nil
	}
	tableDef := tblStuff.baseRel.GetTableDef(ctx)
	if tableDef == nil {
		return tracker, nil
	}
	tracker.dstDB = tableDef.DbName
	for _, col := range tableDef.Cols {
		if col == nil || col.Default == nil {
			continue
		}
		db, seq, ok := reconcilableSequenceDefault(col.Default.Expr)
		if !ok {
			continue
		}
		if db == "" {
			db = tracker.dstDB
		}
		if !tracker.sameDB(db) {
			// A default pinned at another database's sequence is a foreign
			// identity: the merge never reconciles across databases. Under
			// case-sensitive mode a case-differing pin is foreign too.
			continue
		}
		// Resolve the destination default column to the source-side column
		// and then to its index in the apply-row layout (tblStuff.def is
		// built from tarRel).
		tarDef := tblStuff.tarRel.GetTableDef(ctx)
		if tarDef == nil {
			return tracker, nil
		}
		tarCol := dataBranchColumnDefByLogicalName(tarDef, col)
		if tarCol == nil {
			continue
		}
		idx := -1
		for i, name := range tblStuff.def.colNames {
			if strings.EqualFold(name, tarCol.Name) {
				idx = i
				break
			}
		}
		if idx < 0 {
			continue
		}
		tracker.cols[idx] = sequenceWatermarkKey{
			db:    tracker.nameKey(tracker.dstDB),
			table: tracker.nameKey(seq),
		}
	}
	return tracker, nil
}

// reconcilableSequenceDefault reports whether the restored default is a
// single nextval call with constant string arguments, returning the
// (optional) pinned database and the sequence name.
func reconcilableSequenceDefault(expr *plan.Expr) (string, string, bool) {
	for {
		fn := expr.GetF()
		if fn == nil || fn.Func == nil || len(fn.Args) == 0 {
			return "", "", false
		}
		if plan2.IsAssignmentCastFamilyName(fn.Func.GetObjName()) {
			// Planner-owned assignment casts come in two shapes: a
			// single-argument wrapper, or the catalog's two-argument
			// (value, target type) form whose second argument is a type
			// expression. The planner wraps catalog defaults of the wider
			// cast family around nextval for VARCHAR/TEXT families
			// ("cast_strict") and MEDIUMINT (the
			// assignmentCastFunctionName pick), so the whole family must
			// unwrap here — recognizing only "cast" would silently stop
			// tracking the sequence default of those column types (#30359).
			// Unwrap the value in both shapes; anything else (e.g. a user
			// expression with a non-type second argument) is not a
			// reconcilable default, and a transformed inner expression
			// still fails the nextval shape check below.
			if len(fn.Args) == 1 {
				expr = fn.Args[0]
				continue
			}
			if len(fn.Args) == 2 {
				if _, isType := fn.Args[1].Expr.(*plan.Expr_T); isType {
					expr = fn.Args[0]
					continue
				}
			}
			return "", "", false
		}
		if !strings.EqualFold(fn.Func.GetObjName(), "nextval") {
			return "", "", false
		}
		if len(fn.Args) < 1 || len(fn.Args) > 2 {
			return "", "", false
		}
		seq := fn.Args[0].GetLit().GetSval()
		if seq == "" {
			return "", "", false
		}
		db := ""
		if len(fn.Args) == 2 {
			db = fn.Args[1].GetLit().GetSval()
			if db == "" {
				return "", "", false
			}
		}
		return db, seq, true
	}
}

// capture folds one applied row's reconcilable column values into the
// watermarks. kind-filtering happens at the call site; deletes never reach
// here.
func (t *sequenceWatermarkTracker) capture(tblStuff tableStuff, row []any, idxes []int) {
	if t == nil || len(t.cols) == 0 {
		return
	}
	for _, idx := range idxes {
		key, ok := t.cols[idx]
		if !ok || idx >= len(row) || idx >= len(tblStuff.def.colTypes) {
			continue
		}
		val, ok := sequenceWatermarkValueOf(row[idx], tblStuff.def.colTypes[idx])
		if !ok {
			continue
		}
		wm := t.items[key]
		if wm == nil {
			wm = &sequenceWatermark{
				key:   key,
				db:    t.dstDB,
				table: key.table,
			}
			t.items[key] = wm
		}
		wm.rowsCount++
		// Accumulate only the storage-domain arms the value can
		// represent. The sequence's own storage domain — read later from
		// its metadata row — decides which arm reconciles; a column's
		// type (a VARCHAR cast wrapper around a BIGINT UNSIGNED default)
		// never does.
		wm.accumulate(val)
	}
}

// sequenceWatermarkValue is one captured apply-row value classified by the
// numeric domains that can represent it: a value feeds the unsigned arm
// only when 0 <= v <= MaxUint64, the signed arm only when MinInt64 <= v <=
// MaxInt64. Values inside both ranges feed both arms.
type sequenceWatermarkValue struct {
	u    uint64 // unsigned-domain view (valid iff hasU)
	s    uint64 // signed-domain view, sign-extended bits (valid iff hasS)
	hasU bool
	hasS bool
}

func sequenceWatermarkUintValue(u uint64) sequenceWatermarkValue {
	val := sequenceWatermarkValue{u: u, hasU: true}
	if u <= math.MaxInt64 {
		val.s = u
		val.hasS = true
	}
	return val
}

func sequenceWatermarkIntValue(i int64) sequenceWatermarkValue {
	val := sequenceWatermarkValue{s: uint64(i), hasS: true}
	if i >= 0 {
		val.u = uint64(i)
		val.hasU = true
	}
	return val
}

// sequenceWatermarkValueOf converts a typed apply-row value into its
// domain classification. colType carries the extracted column's scale for
// typed decimals: a DECIMAL(p,s) column backed by a nextval default stores
// each issued key as key * 10^s, so integral decimal values normalize by
// the column scale before classification. A stored fraction can never name
// a sequence-issued integral key and stays skipped (#30359 post-PR review:
// typed decimals matched no case here, merge watermarks stayed behind and
// the next default insert regenerated an already-merged key).
func sequenceWatermarkValueOf(v any, colType types.Type) (sequenceWatermarkValue, bool) {
	switch n := v.(type) {
	case int8:
		return sequenceWatermarkIntValue(int64(n)), true
	case int16:
		return sequenceWatermarkIntValue(int64(n)), true
	case int32:
		return sequenceWatermarkIntValue(int64(n)), true
	case int64:
		return sequenceWatermarkIntValue(n), true
	case int:
		return sequenceWatermarkIntValue(int64(n)), true
	case uint8:
		return sequenceWatermarkUintValue(uint64(n)), true
	case uint16:
		return sequenceWatermarkUintValue(uint64(n)), true
	case uint32:
		return sequenceWatermarkUintValue(uint64(n)), true
	case uint64:
		return sequenceWatermarkUintValue(n), true
	case []byte:
		return parseSequenceWatermarkString(string(n))
	case string:
		return parseSequenceWatermarkString(n)
	case types.Decimal64:
		return sequenceDecimal64WatermarkValue(n, colType.Scale)
	case types.Decimal128:
		return sequenceDecimal128WatermarkValue(n, colType.Scale)
	case types.Decimal256:
		return sequenceDecimal256WatermarkValue(n, colType.Scale)
	}
	return sequenceWatermarkValue{}, false
}

func parseSequenceWatermarkString(s string) (sequenceWatermarkValue, bool) {
	if u, err := strconv.ParseUint(s, 10, 64); err == nil {
		return sequenceWatermarkUintValue(u), true
	}
	if i, err := strconv.ParseInt(s, 10, 64); err == nil {
		return sequenceWatermarkIntValue(i), true
	}
	return sequenceWatermarkValue{}, false
}

// sequencePow10Tab holds 10^n for the n values that fit uint64; decimal
// scale divisors below are assembled from these limbs.
var sequencePow10Tab = [...]uint64{
	1, 10, 100, 1000, 10000, 100000, 1000000, 10000000, 100000000,
	1000000000, 10000000000, 100000000000, 1000000000000, 10000000000000,
	100000000000000, 1000000000000000, 10000000000000000, 100000000000000000,
	1000000000000000000, 10000000000000000000,
}

// sequenceIntegralFromMagnitude classifies one integral merged key given as
// magnitude and sign. Non-negative keys classify as unsigned values;
// negative keys classify as signed values, and a magnitude above 2^63
// exceeds even MinInt64's reach, so it cannot be sequence-issued at all.
func sequenceIntegralFromMagnitude(m uint64, negative bool) (sequenceWatermarkValue, bool) {
	if !negative {
		return sequenceWatermarkUintValue(m), true
	}
	if m > 1<<63 {
		return sequenceWatermarkValue{}, false
	}
	// m == 1<<63 wraps to MinInt64 through the int64 negation, which is
	// exactly the representable signed minimum.
	return sequenceWatermarkIntValue(-int64(m)), true
}

// sequenceDecimal64WatermarkValue normalizes a typed DECIMAL64 apply-row
// value. The unscaled integer stores value * 10^scale, so a value names a
// sequence-issued integral key only when it divides exactly by 10^scale.
func sequenceDecimal64WatermarkValue(v types.Decimal64, scale int32) (sequenceWatermarkValue, bool) {
	if scale < 0 {
		return sequenceWatermarkValue{}, false
	}
	negative := v.Sign()
	mag := uint64(int64(v))
	if negative {
		mag = 0 - mag
	}
	if scale >= int32(len(sequencePow10Tab)) {
		// A DECIMAL64 unscaled integer has at most 19 digits, so at a
		// greater scale only the zero value is integral.
		if mag != 0 {
			return sequenceWatermarkValue{}, false
		}
		return sequenceWatermarkUintValue(0), true
	}
	divisor := sequencePow10Tab[scale]
	quotient, remainder := mag/divisor, mag%divisor
	if remainder != 0 {
		return sequenceWatermarkValue{}, false
	}
	return sequenceIntegralFromMagnitude(quotient, negative)
}

// sequenceDecimal128WatermarkValue is the DECIMAL128 counterpart; widths
// 19..38 reach this storage, so the scale fits the same divisor table
// widened to 128 bits.
func sequenceDecimal128WatermarkValue(v types.Decimal128, scale int32) (sequenceWatermarkValue, bool) {
	if scale < 0 || scale > 38 {
		return sequenceWatermarkValue{}, false
	}
	negative := v.Sign()
	if negative {
		v = v.Minus()
	}
	divisor := sequenceDecimal128Divisor(scale)
	quotient, err := v.Div128Trunc(divisor)
	if err != nil {
		return sequenceWatermarkValue{}, false
	}
	remainder, err := v.Mod128(divisor)
	if err != nil {
		return sequenceWatermarkValue{}, false
	}
	if remainder.B0_63 != 0 || remainder.B64_127 != 0 {
		return sequenceWatermarkValue{}, false
	}
	if quotient.B64_127 != 0 {
		// An integral key at or above 2^64 exceeds every storage domain.
		return sequenceWatermarkValue{}, false
	}
	return sequenceIntegralFromMagnitude(quotient.B0_63, negative)
}

// sequenceDecimal128Divisor builds 10^scale for scale in [0, 38].
func sequenceDecimal128Divisor(scale int32) types.Decimal128 {
	if scale <= 19 {
		return types.Decimal128{B0_63: sequencePow10Tab[scale]}
	}
	hi, lo := bits.Mul64(sequencePow10Tab[scale-19], sequencePow10Tab[19])
	return types.Decimal128{B0_63: lo, B64_127: hi}
}

// sequenceDecimal256WatermarkValue is the DECIMAL256 counterpart; widths
// above 38 reach this storage, with scales up to 76.
func sequenceDecimal256WatermarkValue(v types.Decimal256, scale int32) (sequenceWatermarkValue, bool) {
	if scale < 0 || scale > 76 {
		return sequenceWatermarkValue{}, false
	}
	negative := v.Sign()
	if negative {
		v = v.Minus()
	}
	divisor, ok := sequenceDecimal256Divisor(scale)
	if !ok {
		return sequenceWatermarkValue{}, false
	}
	quotient, err := v.Div256Trunc(divisor)
	if err != nil {
		return sequenceWatermarkValue{}, false
	}
	remainder, err := v.Mod256(divisor)
	if err != nil {
		return sequenceWatermarkValue{}, false
	}
	if remainder.B0_63 != 0 || remainder.B64_127 != 0 ||
		remainder.B128_191 != 0 || remainder.B192_255 != 0 {
		return sequenceWatermarkValue{}, false
	}
	if quotient.B64_127 != 0 || quotient.B128_191 != 0 || quotient.B192_255 != 0 {
		// An integral key at or above 2^64 exceeds every storage domain.
		return sequenceWatermarkValue{}, false
	}
	return sequenceIntegralFromMagnitude(quotient.B0_63, negative)
}

// sequenceDecimal256Divisor builds 10^scale for scale in [0, 76] by
// multiplying the limb table into place a uint64 chunk at a time.
func sequenceDecimal256Divisor(scale int32) (types.Decimal256, bool) {
	d := types.Decimal256{B0_63: 1}
	for s := int32(0); s < scale; {
		n := scale - s
		if n > 19 {
			n = 19
		}
		var ok bool
		d, ok = sequenceDecimalMultiplyUint64(d, sequencePow10Tab[n])
		if !ok {
			return types.Decimal256{}, false
		}
		s += n
	}
	return d, true
}

// sequenceDecimalMultiplyUint64 multiplies a non-negative 256-bit unscaled
// value by a uint64 factor, reporting limb overflow.
func sequenceDecimalMultiplyUint64(v types.Decimal256, m uint64) (types.Decimal256, bool) {
	out := v
	var carry uint64
	limbs := [4]*uint64{&out.B0_63, &out.B64_127, &out.B128_191, &out.B192_255}
	for _, p := range limbs {
		hi, lo := bits.Mul64(*p, m)
		sum, c := bits.Add64(lo, carry, 0)
		*p = sum
		carry = hi + c
	}
	return out, carry == 0
}

// extrema projects the captured watermark into the exported decision
// input, preserving the presence flags so a storage-domain arm no captured
// value fit stays empty instead of reading foreign-domain bit patterns.
func (wm *sequenceWatermark) extrema() function.SequenceWatermarkExtrema {
	var ext function.SequenceWatermarkExtrema
	for i := 0; i < int(function.SequenceDomainCount); i++ {
		ext.Arms[i] = function.SequenceWatermarkDomainExtrema{
			Max: wm.arms[i].max,
			Min: wm.arms[i].min,
			Has: wm.arms[i].has,
		}
	}
	return ext
}

func (t *sequenceWatermarkTracker) empty() bool {
	return t == nil || len(t.items) == 0
}

// reconcileMergeSequenceWatermarks runs after every apply batch of a merge
// flushed successfully. Committed generations advance in one fresh committed
// transaction; generations visible only inside the caller (merge)
// transaction advance in-caller. A guard failure or identity change fails
// the merge statement; monotonic conditional updates make merge retries
// no-ops.
func reconcileMergeSequenceWatermarks(ctx context.Context, ses *Session, bh BackgroundExec, tracker *sequenceWatermarkTracker) error {
	if tracker.empty() {
		return nil
	}
	proc := ses.GetProc()
	if proc == nil {
		return moerr.NewInternalErrorNoCtx("data branch merge: missing process for sequence reconciliation")
	}
	// The engine must come from the session's txn handler, not from the
	// statement context: EngineKey is attached only inside compiled
	// statement execution (compile2.go), and the merge driver envelope
	// never guarantees it (observed failing deterministically when the CN
	// runs inside `mo-service -launch`). The txn handler is wired with the
	// CN's engine at service start in every topology.
	var e engine.Engine
	if txnHandler := ses.GetTxnHandler(); txnHandler != nil {
		e = txnHandler.GetStorage()
	}
	if e == nil {
		return moerr.NewInternalErrorNoCtx("data branch merge: missing engine for sequence reconciliation")
	}
	// The txn handler always wraps its storage in *EntireEngine
	// (InitTxnHandler), so a missing engine surfaces as a non-nil interface
	// holding a nil inner engine; guard both layers.
	if ee, ok := e.(*engine.EntireEngine); ok && ee.Engine == nil {
		return moerr.NewInternalErrorNoCtx("data branch merge: missing engine for sequence reconciliation")
	}
	items := make([]*sequenceWatermark, 0, len(tracker.items))
	for _, wm := range tracker.items {
		items = append(items, wm)
	}
	selectSQL := func(wm *sequenceWatermark) string {
		return "select last_seq_num, min_value, max_value, start_value, increment_value, cycle, is_called from " +
			sequenceCommitTableName(wm.db, wm.table) + " for update"
	}
	conditionalUpdate := func(wm *sequenceWatermark, dec function.SequenceWatermarkDecision) string {
		cmp := "<"
		if dec.Descending {
			cmp = ">"
		}
		return fmt.Sprintf(
			"update %s set last_seq_num = %s, is_called = true where last_seq_num %s %s or (last_seq_num = %s and is_called = false)",
			sequenceCommitTableName(wm.db, wm.table), dec.Literal, cmp, dec.Literal, dec.Literal)
	}

	var accountID uint32
	if tenant := ses.GetTenantInfo(); tenant != nil {
		accountID = tenant.GetTenantID()
	}
	// The reconcile unit must not bind its committed transaction to
	// proc.Ctx: the session process context is reseated by statement
	// machinery and can already be dead once the merge's apply pipelines
	// finished, which cancels the unit mid-commit with "context canceled"
	// (observed live). The merge statement context stays alive through the
	// reconcile unit's completion (mergeDiffs defers its cancel).
	hook, _ := ctx.Value(sequenceReconcilePlanHookKey{}).(sequenceReconcilePlanHook)
	envCtx := defines.AttachAccountId(ctx, accountID)
	env, err := function.NewSequenceAutonomousEnv(envCtx, proc, tracker.dstDB)
	if err != nil {
		return err
	}
	// The committed partition: one fresh committed transaction. Misses in
	// its snapshot are transaction-local generations and move to the
	// in-caller partition below.
	var local []*sequenceWatermark
	// The callback's engine resolutions take the attempt's own bounded
	// context (design §4 D H2, the attempt deadline propagation of v22):
	// catalog misses in disttae can run metadata SQL on the supplied
	// context, so without it a blocked resolution overshoots the
	// per-attempt budget and outlives a cancelled attempt, retaining the
	// sequence gate. Statement-local metadata (StatementOption) stays
	// bound to the unit's own statement.
	runErr := env.Run(proc, tracker.dstDB, "data branch merge sequence reconcile", func(attemptCtx context.Context, te executor.TxnExecutor) error {
		local = local[:0]
		type plannedIdentity struct {
			id uint64
			wm *sequenceWatermark
		}
		planned := make([]plannedIdentity, 0, len(items))
		for _, wm := range items {
			dbHandler, err := e.Database(attemptCtx, wm.db, te.Txn())
			if err != nil {
				if isSeqLifecycleMiss(err) {
					local = append(local, wm)
					continue
				}
				return err
			}
			rel, err := dbHandler.Relation(attemptCtx, wm.table, nil)
			if err != nil {
				if isSeqLifecycleMiss(err) {
					local = append(local, wm)
					continue
				}
				return err
			}
			// Only a sequence may ever receive the counter UPDATE below: a
			// same-named ordinary table with sequence-shaped columns is a
			// user relation that the merge must never modify (relkind guard).
			// The failure is deterministic and aborts the merge atomically.
			if err := function.RequireSequenceRel(attemptCtx, rel); err != nil {
				return err
			}
			planned = append(planned, plannedIdentity{id: rel.GetTableID(attemptCtx), wm: wm})
		}
		// A single tenant runs the reconcile, so the relation id alone is
		// the canonical (account, id) order.
		sort.Slice(planned, func(i, j int) bool { return planned[i].id < planned[j].id })
		if hook != nil {
			ids := make([]uint64, len(planned))
			for i, p := range planned {
				ids[i] = p.id
			}
			hook.AfterPlan(ids)
		}
		for _, p := range planned {
			// Validate before proceeding in the canonical catalog-then-data
			// order. The engine re-resolution and the statement share the
			// attempt's pinned in-txn snapshot (WithDisableIncrStatement),
			// so a matching id here binds the generation the SELECT FOR
			// UPDATE resolves; any committed rank change aborts the whole
			// unit and the retry matrix replans from fresh identities.
			dbHandler, err := e.Database(attemptCtx, p.wm.db, te.Txn())
			if err != nil {
				return moerr.NewLockTableBindChanged(attemptCtx)
			}
			rel, err := dbHandler.Relation(attemptCtx, p.wm.table, nil)
			if err != nil || rel.GetTableID(attemptCtx) != p.id {
				return moerr.NewLockTableBindChanged(attemptCtx)
			}
			if err := function.RequireSequenceRel(attemptCtx, rel); err != nil {
				return err
			}
			// The SELECT FOR UPDATE runs through the real statement
			// pipeline: its plan-time catalog fence (the shared
			// mo_catalog.mo_tables row lock of lock_meta.go, held to unit
			// commit) precedes the sequence's data-row lock, and walking
			// the plan in ascending id order accumulates both in the
			// canonical (account, id) order for every concurrent unit.
			res, err := te.Exec(selectSQL(p.wm), env.StatementOption())
			if err != nil {
				return err
			}
			values, err := function.ReadSequenceMetadataRow(attemptCtx, res)
			res.Close()
			if err != nil {
				return err
			}
			if values == nil {
				return moerr.NewInternalError(attemptCtx, "Failed to get sequence meta data.")
			}
			dec, err := function.CheckSequenceWatermark(attemptCtx, values, p.wm.extrema(), p.wm.table)
			if err != nil {
				return err
			}
			if !dec.Transition {
				continue
			}
			res2, err := te.Exec(conditionalUpdate(p.wm, dec), env.StatementOption())
			if err != nil {
				return err
			}
			res2.Close()
		}
		return nil
	})
	if runErr != nil {
		return runErr
	}
	if len(local) == 0 {
		return nil
	}

	// The transaction-local partition advances inside the caller (merge)
	// transaction via the internal executor bound to its operator, so the
	// counter growth shares the merged rows' commit/rollback fate.
	bhTxnOp := backgroundExecTxnOperator(bh)
	if bhTxnOp == nil {
		return moerr.NewInternalErrorNoCtx("data branch merge: missing transaction for local sequence reconciliation")
	}
	lowerCaseTableNames := int64(1)
	if v, e2 := ses.GetSessionSysVar("lower_case_table_names"); e2 == nil && v != nil {
		if n, ok := v.(int64); ok {
			lowerCaseTableNames = n
		}
	}
	opts := executor.Options{}.
		WithDisableIncrStatement().
		WithTxn(bhTxnOp).
		WithKeepTxnAlive().
		WithAccountID(accountID).
		WithLowerCaseTableNames(&lowerCaseTableNames).
		WithDatabase(tracker.dstDB).
		WithTimeZone(ses.GetTimeZone()).
		WithStatementOption(executor.StatementOption{}.WithAccountID(accountID))
	type localIdentity struct {
		id uint64
		wm *sequenceWatermark
	}
	resolved := make([]localIdentity, 0, len(local))
	for _, wm := range local {
		dbHandler, err := e.Database(env.Ctx(), wm.db, bhTxnOp)
		if err != nil {
			return err
		}
		rel, err := dbHandler.Relation(env.Ctx(), wm.table, nil)
		if err != nil {
			return err
		}
		// Same sequence-only boundary as the committed partition: a
		// transaction-local ordinary table look-alike is never modified.
		if err := function.RequireSequenceRel(env.Ctx(), rel); err != nil {
			return err
		}
		resolved = append(resolved, localIdentity{id: rel.GetTableID(env.Ctx()), wm: wm})
	}
	sort.Slice(resolved, func(i, j int) bool { return resolved[i].id < resolved[j].id })
	for _, li := range resolved {
		res, err := env.ExecLocal(selectSQL(li.wm), opts)
		if err != nil {
			return err
		}
		values, err := function.ReadSequenceMetadataRow(env.Ctx(), res)
		res.Close()
		if err != nil {
			return err
		}
		if values == nil {
			return moerr.NewInternalError(env.Ctx(), "Failed to get sequence meta data.")
		}
		dec, err := function.CheckSequenceWatermark(env.Ctx(), values, li.wm.extrema(), li.wm.table)
		if err != nil {
			return err
		}
		if !dec.Transition {
			continue
		}
		res2, err := env.ExecLocal(conditionalUpdate(li.wm, dec), opts)
		if err != nil {
			return err
		}
		res2.Close()
	}
	return nil
}
