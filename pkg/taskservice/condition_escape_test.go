// Regression tests for issue #31303: task names (and the other raw string
// conditions) are interpolated into SQL string literals, so every value must
// be encoded such that the surrounding WHERE clause structure — in particular
// the tenant-scoping account_id conjunct — cannot be altered by the value.

// hostileNames31303 are injected task-name shapes from the issue plus
// escaping-relevant edge cases (quotes, backslashes, comment markers,
// unicode, newlines).
var hostileNames31303 = []string{
	`x' or task_name='sys_side_task' -- `,
	`x' or account_id=0 or '1'='1`,
	`plain_name`,
	``,
	`it's`,
	`x\`,
	`\q'`,
	`a\\b'`,
	`任务'名`,
	"a\nb' -- c",
}

func TestSQLStringValueEscapesLiteralContent(t *testing.T) {
	// Expected values are hardcoded on purpose: they are the independent
	// oracle for the encoding, not generated by the same algorithm.
	for _, tc := range []struct {
		in   string
		want string
	}{
		{``, ``},
		{`plain_name`, `plain_name`},
		{`it's`, `it''s`},
		{`a\b`, `a\\b`},
		{`x\`, `x\\`},
		{`'`, `''`},
		{`\`, `\\`},
		{`\'`, `\\''`},
		{`a\\b'`, `a\\\\b''`},
		{`x' or task_name='sys_side_task' -- `, `x'' or task_name=''sys_side_task'' -- `},
		{`x' or account_id=0 or '1'='1`, `x'' or account_id=0 or ''1''=''1`},
		{`任务'名`, `任务''名`},
		{"a\nb' -- c", "a\nb'' -- c"},
	} {
		if got := sqlStringValue(tc.in); got != tc.want {
			t.Errorf("sqlStringValue(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestStringConditionSQLEncodesValue(t *testing.T) {
	// Every condition whose value is an interpolated raw string must encode
	// the value when rendering the literal. Expected fragments are hardcoded.
	for _, tc := range []struct {
		name string
		code condCode
		cond Condition
		want string
	}{
		{
			name: "task runner escaped", code: CondTaskRunner,
			cond: WithTaskRunnerCond(EQ, "cn1' or '1'='1"),
			want: `task_runner='cn1'' or ''1''=''1'`,
		},
		{
			name: "task runner empty EQ keeps NULL branch", code: CondTaskRunner,
			cond: WithTaskRunnerCond(EQ, ""),
			want: `(task_runner='' or task_runner is NULL)`,
		},
		{
			name: "task parent id escaped", code: CondTaskParentTaskID,
			cond: WithTaskParentTaskIDCond(EQ, "p'x"),
			want: `task_parent_id='p''x'`,
		},
		{
			name: "task type escaped", code: CondTaskType,
			cond: WithTaskType(EQ, "t'x"),
			want: `task_type='t''x'`,
		},
		{
			name: "task metadata id escaped", code: CondTaskMetadataId,
			cond: WithTaskMetadataId(EQ, "m'x"),
			want: `task_metadata_id = 'm''x'`,
		},
		{
			name: "task name escaped", code: CondCdcTaskName,
			cond: WithTaskName(EQ, `x' or task_name='sys_side_task' -- `),
			want: `task_name = 'x'' or task_name=''sys_side_task'' -- '`,
		},
		{
			name: "task name empty", code: CondCdcTaskName,
			cond: WithTaskName(EQ, ""),
			want: `task_name = ''`,
		},
		{
			name: "sql task run status escaped", code: CondSQLTaskRunStatus,
			cond: WithSQLTaskRunStatus(EQ, "failed'"),
			want: `status = 'failed'''`,
		},
		{
			name: "sql task trigger type escaped", code: CondSQLTaskTriggerType,
			cond: WithSQLTaskTriggerType(EQ, "cron'"),
			want: `trigger_type = 'cron'''`,
		},
		{
			name: "sql task runner escaped", code: CondSQLTaskRunner,
			cond: WithSQLTaskRunnerCond(EQ, "cn-x'"),
			want: `runner_cn='cn-x'''`,
		},
	} {
		c := newConditions(tc.cond)
		cond, ok := (*c)[tc.code]
		if !ok {
			t.Fatalf("%s: condition code %v not set", tc.name, tc.code)
		}
		if got := cond.sql(); got != tc.want {
			t.Errorf("%s: sql() = %q, want %q", tc.name, got, tc.want)
		}
	}
}

// TestTaskNameWhereClauseKeepsAccountScoping asserts the security invariant
// from issue #31303 on the real queries the storage executes: for injected
// task-name shapes, the generated SELECT must keep account_id as a mandatory
// AND conjunct and the task_name comparison must be one constant equal to
// the original name. The checks are AST/lexical, not substring searches,
// because a *correctly escaped* literal still contains " or " and "-- ".
func TestTaskNameWhereClauseKeepsAccountScoping(t *testing.T) {
	for _, accID := range []uint32{0, 1} {
		for _, name := range hostileNames31303 {
			conds := newConditions(
				WithTaskName(EQ, name),
				WithAccountID(EQ, accID),
			)
			for _, builder := range []struct {
				name       string
				prefix     string
				buildWhere func(*conditions) string
			}{
				{"sql_task", selectSQLTask, buildSQLTaskWhereClause},
				{"sql_task_run", selectSQLTaskRun, buildSQLTaskRunWhereClause},
			} {
				query := builder.prefix + builder.buildWhere(conds)
				assertScopedQuery(t, builder.name, query, name, accID)
			}
		}
	}

	// Independent hardcoded expectations for the canonical injected shapes
	// from the issue (account 0 / tenant 1); these pin the encoding itself.
	c := newConditions(WithTaskName(EQ, `x' or task_name='sys_side_task' -- `), WithAccountID(EQ, 0))
	if got := buildSQLTaskRunWhereClause(c); got != ` AND task_name = 'x'' or task_name=''sys_side_task'' -- ' AND account_id=0` {
		t.Errorf("run clause = %q", got)
	}
	c = newConditions(WithTaskName(EQ, `x' or account_id=0 or '1'='1`), WithAccountID(EQ, 1))
	if got := buildSQLTaskWhereClause(c); got != ` AND task_name = 'x'' or account_id=0 or ''1''=''1' AND account_id=1` {
		t.Errorf("task clause = %q", got)
	}
	// Trailing backslash must not swallow the closing quote.
	c = newConditions(WithTaskName(EQ, `x\`), WithAccountID(EQ, 0))
	if got := buildSQLTaskWhereClause(c); got != ` AND task_name = 'x\\' AND account_id=0` {
		t.Errorf("backslash clause = %q", got)
	}
}

func assertScopedQuery(t *testing.T, kind, query, name string, accID uint32) {
	t.Helper()

	stmts, err := mysqlparser.Parse(context.Background(), query, 1)
	if err != nil {
		t.Fatalf("%s: storage query no longer parses: %v\nquery: %s", kind, err, query)
	}
	if len(stmts) != 1 {
		t.Fatalf("%s: expected 1 statement, got %d\nquery: %s", kind, len(stmts), query)
	}
	sel, ok := stmts[0].(*tree.Select)
	if !ok {
		t.Fatalf("%s: expected *tree.Select, got %T", kind, stmts[0])
	}
	sc, ok := sel.Select.(*tree.SelectClause)
	if !ok {
		t.Fatalf("%s: expected *tree.SelectClause, got %T", kind, sel.Select)
	}
	if sc.Where == nil {
		t.Fatalf("%s: missing WHERE\nquery: %s", kind, query)
	}

	var walk struct {
		comparisons []*tree.ComparisonExpr
		sawOr       bool
		others      []tree.Expr
	}
	var visit func(e tree.Expr)
	visit = func(e tree.Expr) {
		switch v := e.(type) {
		case *tree.AndExpr:
			visit(v.Left)
			visit(v.Right)
		case *tree.OrExpr:
			walk.sawOr = true
			visit(v.Left)
			visit(v.Right)
		case *tree.ComparisonExpr:
			walk.comparisons = append(walk.comparisons, v)
		default:
			walk.others = append(walk.others, e)
		}
	}
	visit(sc.Where.Expr)

	if walk.sawOr {
		t.Errorf("%s: task name %q produced an OR node in WHERE\nquery: %s", kind, name, query)
	}
	if len(walk.others) != 0 {
		t.Errorf("%s: task name %q produced non-comparison WHERE node %T\nquery: %s", kind, name, walk.others[0], query)
	}

	var sawAccount, sawTaskName bool
	for _, cmp := range walk.comparisons {
		// The fixed "where 1=1" anchor of the storage select renders as a
		// constant=constant comparison; everything else must be column vs
		// constant with an encoded literal value.
		if lv, ok := cmp.Left.(*tree.NumVal); ok {
			if rv, ok2 := cmp.Right.(*tree.NumVal); ok2 &&
				cmp.Op == tree.EQUAL && lv.String() == "1" && rv.String() == "1" {
				continue
			}
			t.Errorf("%s: comparison left side is constant %q, want column reference\nquery: %s",
				kind, lv.String(), query)
			continue
		}
		col, ok := cmp.Left.(*tree.UnresolvedName)
		if !ok {
			t.Errorf("%s: comparison left side is %T, want column reference\nquery: %s", kind, cmp.Left, query)
			continue
		}
		val, ok := cmp.Right.(*tree.NumVal)
		if !ok {
			t.Errorf("%s: comparison right side is %T, want constant\nquery: %s", kind, cmp.Right, query)
			continue
		}
		switch col.ColName() {
		case "account_id":
			if cmp.Op != tree.EQUAL || val.String() != strconv.FormatUint(uint64(accID), 10) {
				t.Errorf("%s: account_id comparison changed: op=%v value=%q\nquery: %s",
					kind, cmp.Op, val.String(), query)
			}
			sawAccount = true
		case "task_name":
			// The comparison must be one constant whose parsed value is
			// byte-identical to the original name: quotes/backslashes kept.
			if cmp.Op != tree.EQUAL || val.String() != name {
				t.Errorf("%s: task_name comparison degraded: op=%v value=%q want %q\nquery: %s",
					kind, cmp.Op, val.String(), name, query)
			}
			sawTaskName = true
		}
	}
	if !sawAccount {
		t.Errorf("%s: account_id conjunct missing from WHERE\nquery: %s", kind, query)
	}
	if !sawTaskName {
		t.Errorf("%s: task_name comparison missing from WHERE\nquery: %s", kind, query)
	}
}

// TestDaemonSharedWhereClauseEncodesStringValues covers the shared daemon /
// daemon-claim WHERE generation (buildWhereClause) which also joins raw
// string conditions: injected runner/parent-id/type fragments must stay
// literal content, not become live SQL.
func TestDaemonSharedWhereClauseEncodesStringValues(t *testing.T) {
	for _, tc := range []struct {
		name string
		code condCode
		cond Condition
		want string
	}{
		{
			name: "task runner",
			code: CondTaskRunner,
			cond: WithTaskRunnerCond(EQ, "cn1' or '1'='1"),
			want: ` AND task_runner='cn1'' or ''1''=''1'`,
		},
		{
			name: "task parent id",
			code: CondTaskParentTaskID,
			cond: WithTaskParentTaskIDCond(EQ, "p' -- "),
			want: ` AND task_parent_id='p'' -- '`,
		},
		{
			name: "task metadata id",
			code: CondTaskMetadataId,
			cond: WithTaskMetadataId(EQ, "m' or '1'='1"),
			want: ` AND task_metadata_id = 'm'' or ''1''=''1'`,
		},
	} {
		c := newConditions(tc.cond)
		if got := buildWhereClause(c); got != tc.want {
			t.Errorf("%s: daemon clause = %q, want %q", tc.name, got, tc.want)
		}
	}
}

// TestParserAcceptsBackquotedHostileTaskName keeps the E4 proof from the
// reproduction stage: the MySQL parser accepts the injected identifier as one
// legal token and the AST carries it verbatim to the handlers.
func TestParserAcceptsBackquotedHostileTaskName(t *testing.T) {
	stmts, err := mysqlparser.Parse(context.Background(),
		"show task runs for `x' or task_name='sys_side_task' -- ` limit 5", 1)
	if err != nil {
		t.Fatalf("parser rejected injected backquoted identifier: %v", err)
	}
	var show *tree.ShowSQLTaskRuns
	for _, s := range stmts {
		if st, ok := s.(*tree.ShowSQLTaskRuns); ok {
			show = st
		}
	}
	if show == nil {
		t.Fatalf("expected ShowSQLTaskRuns, got %#v", stmts)
	}
	if got := string(show.TaskName); got != `x' or task_name='sys_side_task' -- ` {
		t.Fatalf("task name AST mismatch: %q", got)
	}
}
