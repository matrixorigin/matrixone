// The test vectors are specified directly in the public wire format, rather
// than generated by a production encoder which could hide shared mistakes.
var emptyMetadata = []byte{1, 0, 0}

func TestDecodeVariantGoldenValues(t *testing.T) {
	for _, tc := range []struct {
		hex, visible string
		tp           bytejson.TpCode
	}{
		{"00", "null", bytejson.TpCodeLiteral},
		{"04", "true", bytejson.TpCodeLiteral},
		{"08", "false", bytejson.TpCodeLiteral},
		{"0cff", "-1", bytejson.TpCodeInt64},
		{"10ff7f", "32767", bytejson.TpCodeInt64},
		{"1400000080", "-2147483648", bytejson.TpCodeInt64},
		{"18ffffffffffffff7f", "9223372036854775807", bytejson.TpCodeInt64},
		{"200264000000", "1.00", bytejson.TpCodeDecimal},
		{"20029cffffff", "-1.00", bytejson.TpCodeDecimal},
		{"2402ffffffffffffffff", "-0.01", bytejson.TpCodeDecimal},
		{"280001000000000000000100000000000000", "18446744073709551617", bytejson.TpCodeDecimal},
		{"2c00000000", `"1970-01-01"`, bytejson.TpCodeDate},
		{"34ffffffffffffffff", `"1969-12-31 23:59:59.999999"`, bytejson.TpCodeDatetime},
		{"440100000000000000", `"00:00:00.000001"`, bytejson.TpCodeTime},
		{"0d616263", `"abc"`, bytejson.TpCodeString},
		{"4003000000616263", `"abc"`, bytejson.TpCodeString},
		{"3c0300000000ff01", `"AP8B"`, bytejson.TpCodeOpaque},
		{"030000", "[]", bytejson.TpCodeArray},
		{"020000", "{}", bytejson.TpCodeObject},
		{"030300010203000408", "[null, true, false]", bytejson.TpCodeArray},
	} {
		t.Run(tc.hex, func(t *testing.T) {
			data, err := hex.DecodeString(tc.hex)
			require.NoError(t, err)
			bj, err := Decode(context.Background(), emptyMetadata, data)
			require.NoError(t, err)
			require.Equal(t, tc.tp, bj.Type)
			require.Equal(t, tc.visible, bj.String())
		})
	}
	// The key table is alphabetical but payloads are deliberately reversed.
	metadata := []byte{0x11, 2, 0, 1, 2, 'a', 'b'}
	value := []byte{2, 2, 0, 1, 1, 0, 2, 4, 8}
	bj, err := Decode(context.Background(), metadata, value)
	require.NoError(t, err)
	require.Equal(t, `{"a": false, "b": true}`, bj.String())
}

func TestDecodeVariantMalformedAndUnsupported(t *testing.T) {
	for _, metadata := range [][]byte{nil, {2, 0, 0}, {1, 0, 1}, {0xc1, 0, 0}, {0x11, 2, 0, 1, 2, 'b', 'a'}, {1, 1, 0, 1, 0xff}} {
		_, err := Decode(context.Background(), metadata, []byte{0})
		require.Error(t, err, metadata)
	}
	for _, value := range [][]byte{
		nil, {0, 0}, {0x18}, {0x0d, 'a'}, {0x05, 0xff},
		{0x40, 0xff, 0xff, 0xff, 0xff}, {0x20, 39, 0, 0, 0, 0},
		{2, 1, 0, 0, 1, 0}, // field ID absent from dictionary
		{3, 2, 0, 0, 1, 0}, // shared/overlapping array entries
		{0x72, 0, 0, 0, 0}, // large-count object with absent offset table
		{3, 1, 1, 2, 0, 0}, // gap before the first child
		{3, 1, 0, 1, 0, 0}, // trailing bytes
		{3, 1, 0, 2, 0, 0}, // primitive has trailing byte
	} {
		_, err := Decode(context.Background(), emptyMetadata, value)
		require.Error(t, err, value)
	}
	for _, tag := range []byte{12, 18, 19, 20, 63} {
		_, err := Decode(context.Background(), emptyMetadata, []byte{tag << 2})
		require.Error(t, err)
	}
	for _, f := range []float64{math.Inf(1), math.Inf(-1), math.NaN()} {
		data := binary.LittleEndian.AppendUint64([]byte{7 << 2}, math.Float64bits(f))
		_, err := Decode(context.Background(), emptyMetadata, data)
		require.Error(t, err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	_, err := Decode(ctx, emptyMetadata, []byte{0})
	require.ErrorIs(t, err, context.Canceled)
	var d = decoder{remaining: 2}
	require.Error(t, d.charge(3))
	_, err = Decode(context.Background(), emptyMetadata, nestedArrays(101))
	require.ErrorContains(t, err, "nesting")
	_, err = Decode(context.Background(), emptyMetadata, nestedArrays(100))
	require.NoError(t, err)
}

func nestedArrays(depth int) []byte {
	b := []byte{0}
	for i := 0; i < depth; i++ {
		// Four-byte offsets are permitted even when smaller offsets suffice.
		next := []byte{3 | (3 << 2), 1, 0, 0, 0, 0}
		next = binary.LittleEndian.AppendUint32(next, uint32(len(b)))
		b = append(next, b...)
	}
	return b
}

func TestDecodeVariantTenThousandCases(t *testing.T) {
	rng := rand.New(rand.NewSource(20261012))
	metadata := []byte{0x11, 1, 0, 4, 'c', 'o', 's', 't'}
	for i := 0; i < 10000; i++ {
		unscaled := rng.Int63()
		if i%2 == 0 {
			unscaled = -unscaled
		}
		// Decimal16, scale 6, inside an object. Keep the coefficient below
		// 10^18 and compare against independent base-10 formatting.
		unscaled %= 1e18
		number := binary.LittleEndian.AppendUint64([]byte{10 << 2, 6}, uint64(unscaled))
		upper := uint64(0)
		if unscaled < 0 {
			upper = math.MaxUint64
		}
		number = binary.LittleEndian.AppendUint64(number, upper)
		value := append([]byte{2, 1, 0, 0, byte(len(number))}, number...)
		bj, err := Decode(context.Background(), metadata, value)
		require.NoError(t, err, i)
		negative := unscaled < 0
		if negative {
			unscaled = -unscaled
		}
		want := fmt.Sprintf("%d.%06d", unscaled/1e6, unscaled%1e6)
		if negative {
			want = "-" + want
		}
		require.Equal(t, `{"cost": `+want+`}`, bj.String(), i)
		encodedMetadata, encodedValue, err := Encode(context.Background(), bj)
		require.NoError(t, err, i)
		roundTrip, err := Decode(context.Background(), encodedMetadata, encodedValue)
		require.NoError(t, err, i)
		require.Zero(t, bytejson.CompareByteJson(bj, roundTrip), i)
	}
}

func FuzzDecodeVariant(f *testing.F) {
	f.Add(emptyMetadata, []byte{0})
	f.Add(emptyMetadata, []byte{3, 1, 0, 1, 0})
	f.Add([]byte{0x11, 2, 0, 1, 2, 'a', 'b'}, []byte{2, 2, 0, 1, 1, 0, 2, 4, 8})
	f.Fuzz(func(t *testing.T, metadata, value []byte) {
		if len(metadata)+len(value) > 1<<16 {
			return
		}
		bj, err := Decode(context.Background(), metadata, value)
		if err == nil {
			text, err := bj.MarshalJSON()
			require.NoError(t, err)
			require.True(t, json.Valid(text))
			require.True(t, bytejson.IsValidByteJson(bj))
			encodedMetadata, encodedValue, err := Encode(context.Background(), bj)
			require.NoError(t, err)
			roundTrip, err := Decode(context.Background(), encodedMetadata, encodedValue)
			require.NoError(t, err)
			require.Zero(t, bytejson.CompareByteJson(bj, roundTrip))
		}
	})
}
