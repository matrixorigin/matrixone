//go:build linux || darwin

package fileservice

import (
	"errors"
	"os"

	"github.com/matrixorigin/matrixone/pkg/common/moerr"
	"golang.org/x/sys/unix"
)

func openSpillRootLease(path string) (*os.File, error) {
	fd, err := unix.Open(path, unix.O_RDWR|unix.O_CREAT|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0600)
	if err != nil {
		return nil, err
	}
	file := os.NewFile(uintptr(fd), path)
	info, err := file.Stat()
	if err != nil || !info.Mode().IsRegular() {
		_ = file.Close()
		return nil, errors.Join(moerr.NewInternalErrorNoCtx("spill lease must be a regular local file"), err)
	}
	if err := unix.Flock(fd, unix.LOCK_EX|unix.LOCK_NB); err != nil {
		_ = file.Close()
		if errors.Is(err, unix.EWOULDBLOCK) || errors.Is(err, unix.EAGAIN) {
			return nil, errors.Join(ErrSpillRootOwned, err)
		}
		return nil, err
	}
	return file, nil
}
