package api

import "math"

// SaturatingMemoryMul multiplies positive memory sizes, saturating on overflow.
// Nonpositive inputs produce zero.
func SaturatingMemoryMul(left, right int64) int64 {
	if left <= 0 || right <= 0 {
		return 0
	}
	if left > math.MaxInt64/right {
		return math.MaxInt64
	}
	return left * right
}

// SaturatingNonnegativeAdd adds nonnegative values, saturating on overflow.
// Negative inputs are treated as an invalid size and saturate.
func SaturatingNonnegativeAdd(left, right int64) int64 {
	if left < 0 || right < 0 || left > math.MaxInt64-right {
		return math.MaxInt64
	}
	return left + right
}
