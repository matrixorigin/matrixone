package util

// RemoveIf compacts data in place, preserving order and leaving the tail untouched.
func RemoveIf[T any](data []T, pred func(T) bool) []T {
	if len(data) == 0 {
		return data
	}
	res := 0
	for i := 0; i < len(data); i++ {
		if !pred(data[i]) {
			if res != i {
				data[res] = data[i]
			}
			res++
		}
	}
	return data[:res]
}
