type enumIndexBackfillKey struct{}

func isEnumIndexBackfill(ctx context.Context) bool {
	state, _ := ctx.Value(enumIndexBackfillKey{}).(*enumIndexBackfillBinding)
	return state != nil
}

type enumIndexBackfillBinding struct {
	spec          *executor.EnumIndexBackfillSpec
	refs          map[*tree.UnresolvedName]planpb.Type
	sources       map[*tree.TableName]struct{}
	sourceColumns map[string]*planpb.ColDef
	columns       map[string]planpb.Type
	insert        *tree.Insert
}

// WithEnumIndexBackfill only recognizes the exact source and target nodes of
// one generated INSERT or uniqueness check. Separately parsed expressions,
// including generated column expressions, cannot inherit these AST marks.
func WithEnumIndexBackfill(ctx context.Context, stmt tree.Statement, spec *executor.EnumIndexBackfillSpec) (context.Context, error) {
	invalid := func() error { return moerr.NewInvalidInputNoCtx("invalid internal ENUM index backfill") }
	if spec == nil || spec.Source == nil || spec.Target == nil || spec.Index == nil || spec.SourceID == 0 || spec.TargetID == 0 || spec.Database == "" || spec.Source.Name == "" || spec.Index.IndexTableName == "" || !strings.EqualFold(spec.Target.Name, spec.Index.IndexTableName) {
		return nil, invalid()
	}
	account, err := defines.GetAccountId(ctx)
	if err != nil || account != spec.AccountID {
		return nil, invalid()
	}
	wanted := make(map[string]bool)
	for _, part := range spec.Index.Parts {
		wanted[strings.ToLower(catalog.ResolveAlias(part))] = true
	}
	if spec.Source.Pkey != nil {
		wanted[strings.ToLower(spec.Source.Pkey.PkeyColName)] = true
		for _, name := range spec.Source.Pkey.Names {
			wanted[strings.ToLower(name)] = true
		}
	}
	columns := make(map[string]planpb.Type)
	sourceColumns := make(map[string]*planpb.ColDef)
	for _, col := range spec.Source.Cols {
		if col == nil {
			return nil, invalid()
		}
		name := strings.ToLower(col.Name)
		if wanted[name] {
			if sourceColumns[name] != nil {
				return nil, invalid()
			}
			sourceColumns[name] = col
		}
		if wanted[name] && isEnumOrSetPlanType(&col.Typ) {
			if _, exists := columns[name]; exists {
				return nil, invalid()
			}
			columns[name] = col.Typ
		}
	}
	if len(columns) == 0 {
		return nil, invalid()
	}
	state := &enumIndexBackfillBinding{spec: spec, refs: make(map[*tree.UnresolvedName]planpb.Type), sources: make(map[*tree.TableName]struct{}), columns: columns, sourceColumns: sourceColumns}
	directTable := func(expr tree.TableExpr, name string, source bool) error {
		// The parser represents a single FROM relation as a one-sided CROSS
		// join. A real join is never generated by this owner.
		if join, ok := expr.(*tree.JoinTableExpr); ok {
			if join.Right != nil || join.Cond != nil {
				return invalid()
			}
			expr = join.Left
		}
		if alias, ok := expr.(*tree.AliasedTableExpr); ok {
			if alias.As.Alias != "" || len(alias.IndexHints) != 0 {
				return invalid()
			}
			expr = alias.Expr
		}
		table, ok := expr.(*tree.TableName)
		if !ok || table.AtTsExpr != nil || !strings.EqualFold(string(table.SchemaName), spec.Database) || !strings.EqualFold(string(table.ObjectName), name) {
			return invalid()
		}
		if source {
			state.sources[table] = struct{}{}
		}
		return nil
	}
	var selectStmt func(*tree.Select) error
	var scalar func(tree.Expr) error
	scalar = func(e tree.Expr) error {
		if e == nil {
			return invalid()
		}
		switch n := e.(type) {
		case *tree.UnresolvedName:
			if n.Star {
				return nil
			}
			if n.NumParts != 1 {
				return invalid()
			}
			if typ, ok := columns[strings.ToLower(n.ColName())]; ok {
				state.refs[n] = typ
			}
			return nil
		case *tree.NumVal, *tree.UnqualifiedStar, tree.UnqualifiedStar:
			return nil
		case *tree.ParenExpr:
			return scalar(n.Expr)
		case *tree.IsNotNullExpr:
			return scalar(n.Expr)
		case *tree.AndExpr:
			if err := scalar(n.Left); err != nil {
				return err
			}
			return scalar(n.Right)
		case *tree.ComparisonExpr:
			if n.Escape != nil {
				return invalid()
			}
			if err := scalar(n.Left); err != nil {
				return err
			}
			return scalar(n.Right)
		case *tree.FuncExpr:
			name, ok := n.Func.FunctionReference.(*tree.UnresolvedName)
			if !ok || n.WindowSpec != nil {
				return invalid()
			}
			switch strings.ToLower(name.ColName()) {
			case "count", "serial", "serial_full", "physical_serial", "physical_serial_full", "physical_collation_key", "substring":
			default:
				return invalid()
			}
			for _, arg := range n.Exprs {
				if err := scalar(arg); err != nil {
					return err
				}
			}
			return nil
		case *tree.Subquery:
			if n.Exists {
				return invalid()
			}
			switch q := n.Select.(type) {
			case *tree.Select:
				return selectStmt(q)
			case *tree.ParenSelect:
				return selectStmt(q.Select)
			default:
				return invalid()
			}
		default:
			return invalid()
		}
	}
	selectStmt = func(q *tree.Select) error {
		if q == nil || q.With != nil || q.IsPerform || q.TimeWindow != nil || len(q.OrderBy) != 0 || q.RankOption != nil || q.Ep != nil || q.SelectLockInfo != nil {
			return invalid()
		}
		clause, ok := q.Select.(*tree.SelectClause)
		if !ok || clause.Distinct || clause.From == nil || len(clause.From.Tables) != 1 || len(clause.Exprs) == 0 {
			return invalid()
		}
		if err := directTable(clause.From.Tables[0], spec.Source.Name, true); err != nil {
			return err
		}
		for _, e := range clause.Exprs {
			if err := scalar(e.Expr); err != nil {
				return err
			}
		}
		if clause.Where != nil {
			if err := scalar(clause.Where.Expr); err != nil {
				return err
			}
		}
		if clause.GroupBy != nil {
			if clause.GroupBy.Apart || clause.GroupBy.Cube || clause.GroupBy.Rollup || len(clause.GroupBy.GroupingSet) != 0 {
				return invalid()
			}
			for _, group := range clause.GroupBy.GroupByExprsList {
				for _, e := range group {
					if err := scalar(e); err != nil {
						return err
					}
				}
			}
		}
		if clause.Having != nil {
			if err := scalar(clause.Having.Expr); err != nil {
				return err
			}
		}
		return nil
	}
	if spec.DuplicateCheck {
		q, ok := stmt.(*tree.Select)
		if !ok {
			return nil, invalid()
		}
		if err := selectStmt(q); err != nil {
			return nil, err
		}
	} else {
		ins, ok := stmt.(*tree.Insert)
		if !ok || ins.With != nil || ins.Overwrite || len(ins.Columns) != 0 || len(ins.OnDuplicateUpdate) != 0 || ins.HasReturning() {
			return nil, invalid()
		}
		if err := directTable(ins.Table, spec.Index.IndexTableName, false); err != nil {
			return nil, err
		}
		if err := selectStmt(ins.Rows); err != nil {
			return nil, err
		}
		if len(state.refs) == 0 {
			return nil, invalid()
		}
		state.insert = ins
	}
	return context.WithValue(ctx, enumIndexBackfillKey{}, state), nil
}

// WithoutEnumIndexBackfill prevents an internal statement from inheriting a
// parent's marks, even if the nested execution reuses the parent context.
func WithoutEnumIndexBackfill(ctx context.Context) context.Context {
	if ctx == nil || ctx.Value(enumIndexBackfillKey{}) == nil {
		return ctx
	}
	return context.WithValue(ctx, enumIndexBackfillKey{}, (*enumIndexBackfillBinding)(nil))
}

func validateEnumIndexBackfillTarget(ctx context.Context, stmt *tree.Insert, def *planpb.TableDef, obj *planpb.ObjectRef) error {
	state, _ := ctx.Value(enumIndexBackfillKey{}).(*enumIndexBackfillBinding)
	if state == nil || state.insert != stmt {
		return nil
	}
	if def == nil || obj == nil || def.TblId != state.spec.TargetID || uint64(obj.Obj) != state.spec.TargetID || !strings.EqualFold(def.Name, state.spec.Index.IndexTableName) {
		return moerr.NewInvalidInputNoCtx("ENUM index backfill target changed")
	}
	if !sameEnumIndexBackfillTargetLayout(state.spec.Target, def) {
		return moerr.NewInvalidInputNoCtx("ENUM index backfill target schema changed")
	}
	return nil
}

func sameEnumIndexBackfillTargetLayout(expected, actual *planpb.TableDef) bool {
	if expected == nil || actual == nil || !strings.EqualFold(expected.Name, actual.Name) {
		return false
	}
	actualCols := make([]*planpb.ColDef, 0, len(actual.Cols))
	for _, col := range actual.Cols {
		// The catalog materializes a hidden row ID for every physical table;
		// it is not part of the planned index key/payload layout.
		if col != nil && col.Hidden && col.Name == catalog.Row_ID {
			continue
		}
		actualCols = append(actualCols, col)
	}
	if len(expected.Cols) != len(actualCols) {
		return false
	}
	for i, want := range expected.Cols {
		got := actualCols[i]
		if want == nil || got == nil || !strings.EqualFold(want.Name, got.Name) {
			return false
		}
		left, right := want.Typ, got.Typ
		left.Table, right.Table = "", ""
		left.NotNullable, right.NotNullable = false, false
		left.AutoIncr, right.AutoIncr = false, false
		if !proto.Equal(&left, &right) {
			return false
		}
	}
	if (expected.Pkey == nil) != (actual.Pkey == nil) {
		return false
	}
	if expected.Pkey != nil && (expected.Pkey.PkeyColName != actual.Pkey.PkeyColName || !slices.Equal(expected.Pkey.Names, actual.Pkey.Names)) {
		return false
	}
	return true
}

func sameEnumIndexDomain(a, b *planpb.Type) bool {
	return a != nil && b != nil && a.Id == b.Id && a.Width == b.Width && a.Scale == b.Scale && a.Enumvalues == b.Enumvalues && a.EnumCollation == b.EnumCollation && a.EnumEncoding == b.EnumEncoding
}

func validateEnumIndexBackfillSource(ctx context.Context, node *tree.TableName, def *planpb.TableDef, obj *planpb.ObjectRef) error {
	state, _ := ctx.Value(enumIndexBackfillKey{}).(*enumIndexBackfillBinding)
	if state == nil {
		return nil
	}
	if _, ok := state.sources[node]; !ok {
		return nil
	}
	invalid := func() error { return moerr.NewInvalidInputNoCtx("ENUM index backfill source changed") }
	if def == nil || obj == nil || def.TblId != state.spec.SourceID || uint64(obj.Obj) != state.spec.SourceID || !strings.EqualFold(def.Name, state.spec.Source.Name) {
		return invalid()
	}
	seen := make(map[string]bool, len(state.columns))
	for _, col := range def.Cols {
		if col == nil {
			return invalid()
		}
		name := strings.ToLower(col.Name)
		expected, ok := state.columns[name]
		if !ok {
			continue
		}
		if seen[name] || !sameEnumIndexDomain(&col.Typ, &expected) {
			return invalid()
		}
		seen[name] = true
	}
	if len(seen) != len(state.columns) {
		return invalid()
	}
	// Check the physical identity of all source key/PK components against
	// the schema the DDL owner used. ColId may be reused by ALTER; Seqnum is
	// scoped to this verified relation. Nullability and auto-increment affect
	// writes, not the physical representation of an already stored key.
	keySeen := make(map[string]bool, len(state.sourceColumns))
	for _, col := range def.Cols {
		if col == nil {
			return invalid()
		}
		name := strings.ToLower(col.Name)
		expected := state.sourceColumns[name]
		if expected == nil {
			continue
		}
		left, right := col.Typ, expected.Typ
		left.Table, right.Table = "", ""
		left.NotNullable, right.NotNullable = false, false
		left.AutoIncr, right.AutoIncr = false, false
		if keySeen[name] || col.Seqnum != expected.Seqnum || !proto.Equal(&left, &right) {
			return invalid()
		}
		keySeen[name] = true
	}
	if len(keySeen) != len(state.sourceColumns) {
		return invalid()
	}
	return nil
}

func enumIndexPhysicalRef(ctx context.Context, ref *tree.UnresolvedName, binding *Binding, typ *planpb.Type, depth int32) (bool, error) {
	state, _ := ctx.Value(enumIndexBackfillKey{}).(*enumIndexBackfillBinding)
	if state == nil {
		return false, nil
	}
	expected, ok := state.refs[ref]
	if !ok {
		return false, nil
	}
	if depth != 0 || binding == nil || typ == nil || binding.tableID != state.spec.SourceID || !strings.EqualFold(binding.table, state.spec.Source.Name) || !strings.EqualFold(binding.db, state.spec.Database) || !sameEnumIndexDomain(typ, &expected) {
		return false, moerr.NewInvalidInputNoCtx("ENUM index backfill source changed")
	}
	return true, nil
}
