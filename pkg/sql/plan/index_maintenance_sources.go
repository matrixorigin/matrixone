package plan

import (
	"context"
	"strings"

	"github.com/matrixorigin/matrixone/pkg/common/moerr"
	"github.com/matrixorigin/matrixone/pkg/sql/parsers/tree"
	"github.com/matrixorigin/matrixone/pkg/util/executor"
)

type indexMaintenanceSourcesKey struct{}

type indexMaintenanceSource struct {
	base *ObjectRef
	id   uint64
}

// WithIndexMaintenanceSources marks exact table-name nodes in one SQL tree
// generated by an admitted maintenance operator. Separately parsed view, UDF,
// default and user-expression trees do not share these pointer identities.
func WithIndexMaintenanceSources(ctx context.Context, stmt tree.Statement, spec *executor.IndexMaintenanceSpec) (context.Context, error) {
	if err := spec.Validate(); err != nil {
		return nil, err
	}
	sources := make(map[*tree.TableName]indexMaintenanceSource)
	hasRealSource := false
	mark := func(tbl *tree.TableName) {
		if tbl == nil || !strings.EqualFold(string(tbl.SchemaName), spec.Database) || tbl.AtTsExpr != nil {
			return
		}
		for _, target := range spec.Targets {
			if strings.EqualFold(string(tbl.ObjectName), target.Name) {
				sources[tbl] = indexMaintenanceSource{base: &ObjectRef{SchemaName: spec.Database, Obj: int64(spec.BaseID), ObjName: spec.BaseName}, id: target.ID}
				return
			}
		}
	}
	var directTable func(tree.TableExpr) error
	directTable = func(expr tree.TableExpr) error {
		switch n := expr.(type) {
		case *tree.TableName:
			if n.ObjectName != "" {
				hasRealSource = true
			}
			mark(n)
		case *tree.AliasedTableExpr:
			return directTable(n.Expr)
		case *tree.ParenTableExpr:
			return directTable(n.Expr)
		case *tree.JoinTableExpr:
			if n.Right != nil || n.Cond != nil {
				return moerr.NewInvalidInputNoCtx("unexpected index maintenance join")
			}
			return directTable(n.Left)
		case *tree.TableFunction:
			// The token-bound index_file_chunks source is not a relation name.
			hasRealSource = true
		default:
			return moerr.NewInvalidInputNoCtx("unexpected index maintenance table source")
		}
		return nil
	}
	var scalar func(tree.Expr) error
	scalar = func(expr tree.Expr) error {
		switch n := expr.(type) {
		case *tree.ParenExpr:
			return scalar(n.Expr)
		case *tree.BinaryExpr:
			if err := scalar(n.Left); err != nil {
				return err
			}
			return scalar(n.Right)
		case *tree.NumVal, *tree.UnresolvedName:
			return nil
		case *tree.FuncExpr:
			name, ok := n.Func.FunctionReference.(*tree.UnresolvedName)
			if !ok || (!strings.EqualFold(name.ColName(), "greatest") && !strings.EqualFold(name.ColName(), "coalesce") && !strings.EqualFold(name.ColName(), "max")) {
				return moerr.NewInvalidInputNoCtx("unexpected index maintenance scalar")
			}
			for _, arg := range n.Exprs {
				if err := scalar(arg); err != nil {
					return err
				}
			}
			return nil
		case *tree.Subquery:
			var sub *tree.Select
			switch selectNode := n.Select.(type) {
			case *tree.Select:
				sub = selectNode
			case *tree.ParenSelect:
				sub = selectNode.Select
			}
			if sub == nil || sub.With != nil || sub.Limit != nil || len(sub.OrderBy) != 0 {
				return moerr.NewInvalidInputNoCtx("unexpected index maintenance scalar subquery")
			}
			clause, ok := sub.Select.(*tree.SelectClause)
			if !ok || clause.From == nil || len(clause.From.Tables) != 1 || len(clause.Exprs) != 1 || clause.GroupBy != nil || clause.Having != nil {
				return moerr.NewInvalidInputNoCtx("unexpected index maintenance scalar subquery")
			}
			if err := scalar(clause.Exprs[0].Expr); err != nil {
				return err
			}
			return directTable(clause.From.Tables[0])
		default:
			return moerr.NewInvalidInputNoCtx("unexpected index maintenance scalar expression")
		}
	}
	switch n := stmt.(type) {
	case *tree.Select:
		clause, ok := n.Select.(*tree.SelectClause)
		if !ok || n.With != nil {
			return nil, moerr.NewInvalidInputNoCtx("unexpected index maintenance SELECT")
		}
		if clause.From != nil {
			for _, tbl := range clause.From.Tables {
				if err := directTable(tbl); err != nil {
					return nil, err
				}
			}
		}
		// The only generated scalar subqueries occur in a source-less
		// GREATEST/COALESCE/MAX expression. No WHERE or user expression is
		// traversed for marks.
		if !hasRealSource {
			for _, expr := range clause.Exprs {
				if err := scalar(expr.Expr); err != nil {
					return nil, err
				}
			}
		}
	case *tree.Insert:
		if err := directTable(n.Table); err != nil {
			return nil, err
		}
	case *tree.Replace:
		if err := directTable(n.Table); err != nil {
			return nil, err
		}
	case *tree.Delete:
		if n.With != nil || len(n.TableRefs) != 0 || len(n.Tables) != 1 {
			return nil, moerr.NewInvalidInputNoCtx("unexpected index maintenance DELETE")
		}
		if err := directTable(n.Tables[0]); err != nil {
			return nil, err
		}
	default:
		return nil, moerr.NewInvalidInputNoCtx("unexpected index maintenance statement")
	}
	return context.WithValue(ctx, indexMaintenanceSourcesKey{}, sources), nil
}

func resolveIndexMaintenanceSource(ctx CompilerContext, tbl *tree.TableName, database, name string, snapshot *Snapshot, borrowOutput *TableResolution) (*ObjectRef, *TableDef, error) {
	borrowOutput.Reset()
	var sources map[*tree.TableName]indexMaintenanceSource
	if context := ctx.GetContext(); context != nil {
		sources, _ = context.Value(indexMaintenanceSourcesKey{}).(map[*tree.TableName]indexMaintenanceSource)
	}
	source, ok := sources[tbl]
	if !ok {
		return ctx.Resolve(database, name, snapshot, borrowOutput)
	}
	obj, def, err := ctx.ResolveIndexTableByRef(source.base, name, snapshot, nil)
	if err != nil {
		return nil, nil, err
	}
	if obj == nil || def == nil || uint64(obj.Obj) != source.id || def.TblId != source.id {
		return nil, nil, moerr.NewInvalidInputNoCtx("index maintenance relation identity changed")
	}
	return obj, def, nil
}
