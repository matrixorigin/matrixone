func TestRemoteEnumCollationProtocolFloor(t *testing.T) {
	proc := testutil.NewProcess(t)
	rt := moruntime.ServiceRuntime(proc.GetService())
	defer rt.SetGlobalVariables(moruntime.MOProtocolVersion, defines.MORPCLatestVersion)
	rt.SetGlobalVariables(moruntime.MOProtocolVersion, defines.MORPCVersion11)
	wire, err := (&pipeline.Pipeline{DataSource: &pipeline.Source{TableDef: &plan.TableDef{
		EnumUnsupportedDefault: "utf8mb4_unicode_ci",
	}}}).Marshal()
	require.NoError(t, err)
	_, err = decodeScope(wire, proc, true, nil)
	require.ErrorContains(t, err, "protocol version 12")
}
