"""Extract MySQL 8.4 interoperability numbers/names, not implementation code.

Usage: python3 digest_tokens_gen.py --source-dir /path/to/mysql-8.4.11/sql \
    --case-source /path/to/mysql-8.4.11/strings/ctype-utf8.cc
The token inputs come from https://github.com/mysql/mysql-server/tree/mysql-8.4.11/sql.
Identifier case pairs come from my_unicase_default in MySQL 8.4.11.
The upstream implementation is not vendored or required to build MatrixOne.
"""

import argparse
import hashlib
import json
import pathlib
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-dir", type=pathlib.Path, required=True)
parser.add_argument("--case-source", type=pathlib.Path, required=True)
args = parser.parse_args()
files = {name: (args.source_dir / name).read_text() for name in (
    "sql_yacc.yy", "sql_hints.yy", "lex.h", "gen_lex_token.cc"
)}
numbers = {}
for name in ("sql_yacc.yy", "sql_hints.yy"):
    numbers.update((token, int(number)) for token, number in re.findall(
        r"^%token\s*(?:<[^>]+>\s+)?(\w+)\s+(\d+)\b", files[name], re.M))

nonreserved = set(re.findall(r"^%token<lexer.keyword>\s+(\w+)", files["sql_yacc.yy"], re.M))
symbols, hints, text = {}, {}, {}
for token, spelling in re.findall(r'\.set_token\((\w+),\s*"([^"]*)",', files["gen_lex_token.cc"]):
    text[numbers[token]] = spelling
for group, spelling, token in re.findall(r'\{(SYM(?:_FN|_H|_HK)?)\("([^"]+)",\s*(\w+)\)\}', files["lex.h"]):
    number = numbers[token]
    text[number] = spelling
    if group == "SYM_H":
        hints[spelling] = number
    else:
        symbols[spelling] = (number, group == "SYM_FN", group != "SYM_FN" and token not in nonreserved)

starts = set()
for token in re.findall(r"set_start_expr_token\(([^)]+)\);", files["gen_lex_token.cc"]):
    starts.add(ord(token[1]) if token.startswith("'") else numbers[token])

quote = lambda value: json.dumps(value, ensure_ascii=False)
header = pathlib.Path(__file__).read_text().split('"""', 1)[0].splitlines()[1:]
output = [line.replace("#", "//", 1) for line in header]
output += ["// Code generated by digest_tokens_gen.py; DO NOT EDIT.",
           "// MySQL 8.4.11 token/keyword interoperability data."]
for name, source in files.items():
    output.append(f"// {name}: SHA256 {hashlib.sha256(source.encode()).hexdigest()}")
output += ["", "package mysql", "", "const ("]
for name, token in {
    "digestIn": "IN_SYM", "digestNotHigh": "NOT2_SYM",
    "digestOr": "OR2_SYM", "digestConcat": "OR_OR_SYM", "digestAssign": "SET_VAR",
    "digestCharset": "UNDERSCORE_CHARSET", "digestJSONExtract": "JSON_SEPARATOR_SYM",
    "digestJSONUnquote": "JSON_UNQUOTED_SEPARATOR_SYM", "digestWithRollup": "WITH_ROLLUP_SYM",
}.items():
    output.append(f"\t{name} uint16 = {numbers[token]}")
output += [")", "", "var digestSymbols = map[string]digestSymbol{"]
for spelling, (number, function, reserved) in sorted(symbols.items()):
    output.append(f"\t{quote(spelling)}: {{{number}, {str(function).lower()}, {str(reserved).lower()}}},")
output += ["}", "", "var digestHintSymbols = map[string]uint16{"]
for spelling, number in sorted(hints.items()):
    output.append(f"\t{quote(spelling)}: {number},")
output += ["}", "", "var digestTokenText = map[uint16]string{"]
for number, spelling in sorted(text.items()):
    output.append(f"\t{number}: {quote(spelling)},")
output += ["}", "", "var digestExpressionPrefixes = map[uint16]bool{"]
for number in sorted(starts):
    output.append(f"\t{number}: true,")
output += ["}", ""]
path = pathlib.Path(__file__).with_name("digest_tokens.go")
path.write_text("\n".join(output))
subprocess.run(["gofmt", "-w", str(path)], check=True)

# Extract only Unicode interoperability facts, not the upstream implementation.
source = args.case_source.read_text()
pages = re.search(r"my_unicase_pages_default\[256\] = \{(.*?)\};", source, re.S)[1]
names = re.findall(r"plane\w+|nullptr", pages)
assert len(names) == 256
pairs = []
for page, name in enumerate(names):
    if name == "nullptr":
        continue
    rows = re.search(r"\b" + name + r"\[\] = \{(.*?)\};", source, re.S)[1]
    rows = re.findall(r"\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\}", rows)
    assert len(rows) == 256
    for index, row in enumerate(rows):
        code, lower = page * 256 + index, int(row[1], 16)
        if code != lower:
            pairs.append((code, lower))
case_output = [line.replace("#", "//", 1) for line in header]
case_output += ["// Code generated by digest_tokens_gen.py; DO NOT EDIT.",
                "// MySQL 8.4.11 my_unicase_default identifier lowercase pairs.",
                f"// ctype-utf8.cc: SHA256 {hashlib.sha256(source.encode()).hexdigest()}",
                "", "package mysql", "", "var digestIdentifierLower = [...][2]rune{"]
case_output += [f"\t{{0x{code:04X}, 0x{lower:04X}}}," for code, lower in pairs]
case_output += ["}", ""]
case_path = pathlib.Path(__file__).with_name("digest_identifier_case.go")
case_path.write_text("\n".join(case_output))
subprocess.run(["gofmt", "-w", str(case_path)], check=True)
