"""从固定 MySQL 8.4.11 item_create.cc 再生 digest 建树参数边界。"""

import argparse
import collections
import hashlib
import pathlib
import re
import subprocess


def extract(source):
    classes = {}
    for match in re.finditer(r"class (\w+)\s*\{\s*public:\s*static (?:const uint|constexpr int) Min_argcount = (\w+);\s*static (?:const uint|constexpr int) Max_argcount = (\w+);", source):
        classes[match[1]] = (match[2], match[3])
    aliases = {m[1]: (m[2], m[3]) for m in re.finditer(r"using (\w+)\s*=\s*(\w+)\s*<([^;]+)>;", source)}

    def bounds(name):
        seen = set()
        arguments = ""
        while name not in classes:
            assert name not in seen, name
            seen.add(name)
            name, arguments = aliases[name]
        low, high = classes[name]
        if low == "Min_argc":
            assert name == "Instantiator_with_functype" and high == "Max_argc"
            low = high = arguments.split(",")[-1].strip()
        return low, high

    def number(value):
        return -1 if value == "MAX_ARGLIST_SIZE" else int(value)

    table = source[source.index("static const std::pair<const char *, Create_func *> func_array[]"):]
    # Release Oracle 没有 NDEBUG 专用调试函数；未知 SP 名称不套用调试签名。
    table = re.sub(r"#ifndef NDEBUG\n.*?#endif", "", table, flags=re.S)
    assert not re.search(r"^\s*#(?:if|el)", table, flags=re.M)
    rows = re.findall(r'\{"([^"]+)",\s*(\w+)\(([^{}]+?)\)\}', table)
    assert len(rows) == 345
    rules = {}
    for name, macro, parameters in rows:
        if "INTERNAL" in macro:
            continue  # 内部系统视图准入不是这里的公共参数数目契约。
        parameters = [p.strip() for p in parameters.split(",")]
        if macro == "SQL_FACTORY":
            low, high = bounds(parameters[0])
        elif macro in ("SQL_FN", "SQL_FN_LIST"):
            low = high = parameters[1]
        else:
            assert macro in ("SQL_FN_V", "SQL_FN_V_THD", "SQL_FN_V_LIST", "SQL_FN_V_LIST_THD", "SQL_FN_ODD", "SQL_FN_EVEN"), macro
            low, high = parameters[1:]
        rules[name.lower()] = (number(low), number(high), {"SQL_FN_ODD": 1, "SQL_FN_EVEN": 2}.get(macro, 0))
    return rules


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path(__file__).with_name("statement_digest_functions_generated.go"))
    args = parser.parse_args()
    source = args.source.read_bytes()
    assert hashlib.sha256(source).hexdigest() == "8f82c4c9c354afa8276e762b19243397ea405f0780ce6f9e099280af8e5f5532", "需要固定 MySQL 8.4.11 源文件"
    rules = extract(source.decode())
    grouped = collections.defaultdict(list)
    for name, rule in rules.items():
        grouped[rule].append(name)
    header = pathlib.Path(__file__).read_text().split('"""')[0].splitlines()[1:]
    out = "\n".join("//" + line[1:] for line in header).rstrip() + "\n\n"
    out += "// Code generated by digest_functions_gen.py; DO NOT EDIT.\n"
    out += "// MySQL 8.4.11 sql/item_create.cc SHA256: " + hashlib.sha256(source).hexdigest() + "\n"
    out += "// 公共 Function_factory/Instantiator 参数边界，不含内部系统视图工厂。\n"
    out += "package mysql\n\n"
    out += "func digestBuiltinArgumentCount(name string, count int) bool {\n\tswitch name {\n"
    for (low, high, parity), names in sorted(grouped.items()):
        for i in range(0, len(names), 6):
            quoted = ", ".join('"' + name.upper() + '"' for name in sorted(names)[i:i + 6])
            out += ("\tcase " if i == 0 else "\t\t") + quoted
            out += ":\n" if i + 6 >= len(names) else ",\n"
        condition = f"count == {low}" if low == high else f"count >= {low}"
        if low != high and high >= 0:
            condition += f" && count <= {high}"
        if parity:
            condition += f" && count%2 == {parity % 2}"
        out += "\t\treturn " + condition + "\n"
    out += "\tdefault:\n\t\treturn true\n\t}\n}\n"
    args.output.write_text(out)
    subprocess.run(["gofmt", "-w", str(args.output)], check=True)


if __name__ == "__main__":
    main()
