-- Issues #30217, #30214, #30213.
-- MySQL diagnostic codes, fallback values and row counts survive binding and folding.
drop database if exists scalar_compat_warnings;
create database scalar_compat_warnings;
use scalar_compat_warnings;
create table warning_rows(id int primary key, x double, locale varchar(20), date_text varchar(40));
insert into warning_rows values(1,0,'bad_locale','bad'),(2,1,'de_DE','2024-01-02'),(3,null,null,null);
select format(1234.5,2,'bad_locale') as v;
show warnings;
select format('1234.5',2,'') as v;
show warnings;
select format(1234.5,2,null) as v;
show warnings;
select format(1234.5,2,'de_DE') as v;
show warnings;
select format(1234.5,2,'bad_locale') as v from warning_rows order by id;
show count(*) warnings;
show warnings;
select ln(0) as v from warning_rows order by id;
show count(*) warnings;
show warnings;
select log(1,2) as v from warning_rows order by id;
show count(*) warnings;
show warnings;
select str_to_date('bad','%Y-%m-%d') as v from warning_rows order by id;
show count(*) warnings;
show warnings;
select str_to_date('2024-01-02xyz','%Y-%m-%d') as v from warning_rows order by id;
show count(*) warnings;
show warnings;
select ln(x) as v from warning_rows order by id;
show warnings;
select log(2,x) as v from warning_rows order by id;
show warnings;
select log2(x) as v from warning_rows order by id;
show warnings;
select log10(x) as v from warning_rows order by id;
show warnings;
select format(1234.5,2,locale) as v from warning_rows order by id;
show warnings;
select str_to_date(date_text,'%Y-%m-%d') as v from warning_rows order by id;
show warnings;
select str_to_date('2024-02-30','%Y-%m-%d') as v from warning_rows order by id;
show warnings;
select str_to_date('2024-01-02 10:30:45xyz','%Y-%m-%d %H:%i:%s') as v from warning_rows order by id;
show warnings;
select str_to_date('10:30:45xyz','%H:%i:%s') as v from warning_rows order by id;
show warnings;
select case when id=2 then str_to_date(date_text,'%Y-%m-%d') else null end as v from warning_rows order by id;
show warnings;
select case when id=2 then ln(x) else null end as v from warning_rows order by id;
show warnings;
prepare warning_stmt from "select ln(?) as v from warning_rows order by id";
set @bad=0;
execute warning_stmt using @bad;
show count(*) warnings;
set @good=1;
execute warning_stmt using @good;
show count(*) warnings;
deallocate prepare warning_stmt;
-- UTF-8 diagnostics preserve complete characters at the 128-byte echo bound.
select format(1234.5,2,repeat('界',43)) as v;
show warnings;
select format(1234.5,2,concat('a',repeat('😀',32))) as v;
show warnings;
select str_to_date(repeat('界',43),'%Y-%m-%d') as v;
show warnings;
select str_to_date(concat('a',repeat('😀',32)),'%Y-%m-%d') as v;
show warnings;
select str_to_date(concat('2024-01-02',repeat('界',43)),'%Y-%m-%d') as v;
show warnings;
set max_error_count=0;
select format(1234.5,2,repeat('X',129)) as v from warning_rows order by id;
show count(*) warnings;
show warnings;
set max_error_count=default;
drop database scalar_compat_warnings;
