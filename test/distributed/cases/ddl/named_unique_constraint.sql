-- Issue #31659: CREATE TABLE must keep an explicitly named UNIQUE constraint
-- (CONSTRAINT symbol UNIQUE(...)) instead of overwriting the name with the
-- first column's name. MySQL 8.0 keeps the declared symbol, SHOW INDEX/SHOW
-- CREATE TABLE must report it and DROP INDEX must accept it. Explicit
-- "UNIQUE KEY name(...)", anonymous inline UNIQUE, composite keys and the
-- already-correct ALTER ADD CONSTRAINT path are the controls.
DROP DATABASE IF EXISTS named_unique_constraint;
CREATE DATABASE named_unique_constraint;
USE named_unique_constraint;

-- 1. Declared symbol is preserved, visible and droppable.
DROP TABLE IF EXISTS t_named;
CREATE TABLE t_named(id INT PRIMARY KEY, k INT, CONSTRAINT uq_named UNIQUE(k));
SHOW INDEX FROM t_named;
SHOW CREATE TABLE t_named;
SELECT index_name FROM information_schema.statistics WHERE table_schema = 'named_unique_constraint' AND table_name = 't_named' ORDER BY index_name;

-- The preserved unique index still rejects duplicates without mutating rows.
INSERT INTO t_named VALUES (1, 7);
INSERT INTO t_named VALUES (2, 7);
SELECT COUNT(*) FROM t_named;
SELECT 1;

ALTER TABLE t_named DROP INDEX uq_named;
SHOW CREATE TABLE t_named;

-- 2. An explicit index name keeps overriding the constraint symbol.
DROP TABLE IF EXISTS t_both;
CREATE TABLE t_both(id INT PRIMARY KEY, k INT, CONSTRAINT uq_symbol UNIQUE KEY uq_explicit(k));
SHOW INDEX FROM t_both;
ALTER TABLE t_both DROP INDEX uq_explicit;

-- 3. Anonymous inline unique keeps the column-derived autogenerated name.
DROP TABLE IF EXISTS t_anon;
CREATE TABLE t_anon(id INT PRIMARY KEY, k INT UNIQUE);
SHOW INDEX FROM t_anon;
ALTER TABLE t_anon DROP INDEX k;

-- 4. Composite named unique constraint is preserved as a whole.
DROP TABLE IF EXISTS t_composite;
CREATE TABLE t_composite(id INT PRIMARY KEY, a INT, b INT, CONSTRAINT uq_pair UNIQUE(a, b));
SHOW INDEX FROM t_composite;
ALTER TABLE t_composite DROP INDEX uq_pair;

-- 5. A symbol colliding with another declared constraint name is rejected
--    (case-insensitive on final effective names) and creates no table.
CREATE TABLE t_dup(id INT PRIMARY KEY, a INT, b INT, CONSTRAINT uq_dup UNIQUE(a), UNIQUE KEY UQ_DUP(b));
SHOW TABLES;
DROP TABLE IF EXISTS t_dup;

-- 6. The ALTER ADD CONSTRAINT path that already preserved the symbol keeps working.
DROP TABLE IF EXISTS t_alter;
CREATE TABLE t_alter(id INT PRIMARY KEY, k INT);
ALTER TABLE t_alter ADD CONSTRAINT uq_added UNIQUE(k);
SHOW INDEX FROM t_alter;
ALTER TABLE t_alter DROP INDEX uq_added;

DROP DATABASE IF EXISTS named_unique_constraint;
