-- Transaction-local clones share physical objects but not logical deletes.
drop database if exists clone_delete_ownership;
create database clone_delete_ownership;
use clone_delete_ownership;
set session transaction_isolation='READ-COMMITTED';
begin;
create table original(id int primary key, a int, b int);
insert into original values (1,10,100),(2,20,200),(3,30,300);
create index ia on original(a);
create table a clone original;
create table b clone a;
delete from a where id=1;
update a set a=11 where id=2;
select id,a,b from original order by id;
select id,a,b from a order by id;
select id,a,b from b order by id;
commit;
select id,a,b from original order by id;
select id,a,b from a order by id;
select id,a,b from b order by id;
select id from original where a=20;
select id from a where a=11;
select id from b where a=20;
select count(*) as old_key_rows from a where a=20;
begin;
delete from b where id=2;
rollback;
select id,a,b from b order by id;
set session transaction_isolation=default;
drop database clone_delete_ownership;
