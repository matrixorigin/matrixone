-- Transaction-local clones share physical objects but not logical deletes.
drop database if exists clone_delete_ownership;
create database clone_delete_ownership;
use clone_delete_ownership;
set session transaction_isolation='READ-COMMITTED';
begin;
create table original(id int primary key, a int, b int);
insert into original values (1,10,100),(2,20,200),(3,30,300);
create index ia on original(a);
create table a clone original;
create table b clone a;
delete from a where id=1;
update a set a=11 where id=2;
select id,a,b from original order by id;
select id,a,b from a order by id;
select id,a,b from b order by id;
commit;
select id,a,b from original order by id;
select id,a,b from a order by id;
select id,a,b from b order by id;
select id from original where a=20;
select id from a where a=11;
select id from b where a=20;
select count(*) as old_key_rows from a where a=20;
begin;
delete from b where id=2;
rollback;
select id,a,b from b order by id;
-- A cloned tombstone must only filter reads of its owning table.
create table persisted(id int primary key);
insert into persisted values (1),(2),(3);
set @flush_result = (select mo_ctl('dn','flush','clone_delete_ownership.persisted'));
create table persisted_a clone persisted;
delete from persisted_a where id=1;
begin;
create table persisted_b clone persisted_a;
select id from persisted order by id;
select id from persisted_a order by id;
select id from persisted_b order by id;
rollback;
begin;
create table persisted_b clone persisted_a;
select id from persisted order by id;
commit;
select id from persisted order by id;
select id from persisted_b order by id;
-- Rewriting the clone must keep deletes that were already visible at creation.
create table inherited_deletes(id int primary key);
insert into inherited_deletes values (1),(2),(3),(4);
set @flush_result = (select mo_ctl('dn','flush','clone_delete_ownership.inherited_deletes'));
delete from inherited_deletes where id=2;
set @flush_result = (select mo_ctl('dn','flush','clone_delete_ownership.inherited_deletes'));
begin;
create table rewritten clone inherited_deletes;
select id from rewritten order by id;
delete from rewritten where id=3;
select id from rewritten order by id;
select id from inherited_deletes order by id;
commit;
select id from rewritten order by id;
set session transaction_isolation=default;
drop database clone_delete_ownership;
