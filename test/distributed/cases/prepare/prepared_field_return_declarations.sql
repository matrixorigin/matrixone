-- 投影声明与返回值的数值生命周期；显式CAST比较项不声明NULLIF返回域。
SELECT 'scalar_parens';
SET @p0=0,@p1=NULL,@p2='a';
PREPARE p FROM 'select field(case when ? then null else (select (?)) end,?)';
EXECUTE p USING @p0,@p1,@p2;
SET @p1='A',@p2='a';
EXECUTE p USING @p0,@p1,@p2;
SET @p1=CAST('A' AS BINARY);
EXECUTE p USING @p0,@p1,@p2;
DEALLOCATE PREPARE p;
