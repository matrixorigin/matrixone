-- MySQL 8.4 parity coverage: every statement below returns the same result on MySQL 8.4.9.
drop database if exists cov_win;
create database cov_win;
use cov_win;
create table w (id int primary key, g int, v int, s varchar(10));
insert into w values (1,1,10,'a'),(2,1,20,'b'),(3,1,20,'c'),(4,2,5,'d'),(5,2,NULL,'e'),(6,3,7,'f');
select id, row_number() over (partition by g order by v, id) from w order by id;
select id, rank() over (order by v), dense_rank() over (order by v) from w order by id;
select id, percent_rank() over (order by v), cume_dist() over (order by v) from w order by id;
select id, ntile(4) over (order by id) from w order by id;
select id, lag(v) over (order by id), lead(v, 2, -1) over (order by id) from w order by id;
select id, first_value(v) over (partition by g order by id), last_value(v) over (partition by g order by id rows between unbounded preceding and unbounded following) from w order by id;
select id, nth_value(v, 2) over (partition by g order by id) from w order by id;
select id, sum(v) over (order by id rows between 1 preceding and 1 following) from w order by id;
select id, sum(v) over (order by v range between 5 preceding and current row) from w order by id;
select id, avg(v) over (partition by g) from w order by id;
select id, count(*) over (), count(v) over () from w order by id;
select id, sum(v) over w1 from w window w1 as (partition by g order by id) order by id;
select g, sum(v), group_concat(s order by s desc separator '|') from w group by g order by g;
select g, count(distinct v), max(s), min(v) from w group by g having count(*) > 1 order by g;
select bit_and(v), bit_or(v), bit_xor(v) from w;
select std(v), stddev_samp(v), variance(v), var_samp(v) from w;
select group_concat(distinct v order by v) from w;
select g, v, sum(v) over (partition by g order by v) from w order by id;
select id, max(v) over (order by id rows 2 preceding) from w order by id;
select id, lag(v, 0) over (order by id) from w order by id;
select id, ntile(0) over (order by id) from w;
select id, nth_value(v, 0) over (order by id) from w;
select id, lead(v, -1) over (order by id) from w;
select sum(v) over () from w limit 1;
select id, sum(v) over (order by id groups between 1 preceding and current row) from w;
select avg(distinct v) from w;
